-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 1번 표 — 회원별 실제 값                                                   │
-- │                                                                          │
-- │ 여기가 핵심입니다. "전체거래" 와 "확정손익" 두 칸만 보면 됩니다.            │
-- └──────────────────────────────────────────────────────────────────────────┘

select
  '1번 회원별 실제값'                                as 구분,
  p.nickname                                        as 닉네임,
  ta.cycle_no                                       as 계좌사이클,
  round(ta.balance)                                 as 지갑,
  round(ta.initial_balance)                         as 시작돈,
  round(ta.realized_pnl)                            as 확정손익,
  (select count(*) from public.trades t
     where t.user_id = p.id)                        as 전체거래,
  (select count(*) from public.trades t
     where t.user_id = p.id
       and coalesce(t.cycle_no,1) = coalesce(ta.cycle_no,1))
                                                    as 이번사이클거래,
  (select round(sum(t.pnl)) from public.trades t
     where t.user_id = p.id)                        as 거래손익합,
  (select round(sum(t.pnl)) from public.trades t
     where t.user_id = p.id
       and coalesce(t.cycle_no,1) = coalesce(ta.cycle_no,1))
                                                    as 이번사이클손익합,
  (ta.updated_at at time zone 'Asia/Seoul')         as 계좌마지막변경
from public.profiles p
join public.trading_accounts ta on ta.user_id = p.id
order by p.nickname;


-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 2번 표 — 랭킹 함수가 어느 버전인지                                        │
-- │                                                                          │
-- │ get_leaderboard 가 파일 4벌에 서로 다르게 들어 있습니다.                   │
-- │ 어느 것이 서버에 살아 있느냐에 따라 "0" 의 뜻이 달라집니다.                │
-- └──────────────────────────────────────────────────────────────────────────┘

select
  '2번 랭킹함수'                                     as 구분,
  p.proname                                         as 함수이름,
  case
    when pg_get_functiondef(p.oid) ilike '%least(0%'
      or pg_get_functiondef(p.oid) ilike '%바닥%'
      or pg_get_functiondef(p.oid) ilike '%running%'   then '바닥치기 방식 (0에서 끊음)'
    when pg_get_functiondef(p.oid) ilike '%greatest(0%'                then '0 이하 잘라내기 방식'
    else                                                                 '날것 realized_pnl 방식'
  end                                               as 계산방식,
  pg_get_functiondef(p.oid)                         as 함수전문
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.proname in ('get_leaderboard', 'rank_points_all');


-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 3번 표 — 지갑을 시작값으로 되돌리는 트리거가 어느 쪽인지                    │
-- │                                                                          │
-- │ 예전에 "지갑만 100,000 으로 고정되는" 버그가 두 번 있었습니다.             │
-- │ 고친 파일이 있는데, 그게 서버에 반영돼 있는지 파일만 봐서는 모릅니다.       │
-- └──────────────────────────────────────────────────────────────────────────┘

select
  '3번 지갑트리거'                                   as 구분,
  p.proname                                         as 함수이름,
  case
    when pg_get_functiondef(p.oid) ilike '%if exists%trading_accounts%'
      then '✅ 고친 쪽 (기존 계정은 안 건드림)'
    else '❌ 고장난 쪽 — supabase/지갑초기화-해결.sql 을 Run 하면 됩니다'
  end                                               as 판정,
  pg_get_functiondef(p.oid)                         as 함수전문
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public'
  and p.proname in ('force_starting_balance', 'set_starting_balance');


-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 4번 표 — 랭킹이 쓰는 뷰가 있는지                                          │
-- │                                                                          │
-- │ ranking_profit 뷰가 없으면 화면이 조용히 다른 계산으로 넘어갑니다.         │
-- └──────────────────────────────────────────────────────────────────────────┘

select
  '4번 뷰존재'                                       as 구분,
  이름                                              as 뷰이름,
  case when to_regclass(이름) is null
       then '❌ 없음'
       else '✅ 있음' end                            as 있나,
  case when to_regclass(이름) is null
       then null
       else pg_get_viewdef(to_regclass(이름), true) end  as 뷰전문
from (values ('public.ranking_profit'), ('public.leaderboard')) as v(이름);


-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 5번 표 — 누가 초기화를 눌렀는지                                           │
-- │                                                                          │
-- │ 관리자 계좌 초기화가 실행됐다면 여기 흔적이 남습니다. 비어 있으면 안 눌린 것.│
-- └──────────────────────────────────────────────────────────────────────────┘

select
  '5번 초기화이력'                                   as 구분,
  c.*
from public.trading_cycles c
order by c.ended_at desc nulls last
limit 10;


-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ 6번 표 — 랭킹 화면에 실제로 나가는 값                                     │
-- │                                                                          │
-- │ 화면이 보는 것과 똑같은 값을 그대로 불러봅니다.                            │
-- └──────────────────────────────────────────────────────────────────────────┘

select '6번 랭킹실제출력' as 구분, * from public.get_leaderboard();


