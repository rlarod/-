--
--   무엇을 알아내려는 건가
--
--   랭킹에 세 명 전부 "총자산 100,000 / 수익금 0" 으로 뜹니다.
--   그런데 채팅에는 김갱님 거래 7건이 찍혀 있습니다.
--
--   ⚠️ 중요 — 이 0 은 고장이 아닐 수도 있습니다.
--
--   우리 랭킹 규칙은 "잃으면 0 에서 끊긴다" 입니다.
--   김갱님 거래 7건을 그 규칙에 넣고 계산해 보면 결과가 정확히 0 입니다.
--   마지막 강제청산(-338,235,972원)이 그때까지 쌓은 239,873,863원을
--   전부 밀어냈기 때문입니다.
--
--   그래서 화면만으로는 두 경우를 가릴 수가 없습니다.
--       (가) 진짜로 다 잃어서 0        ← 정상
--       (나) 기록이 날아가서 0          ← 고장
--
--   이 파일은 그 둘을 가릅니다. 서버 값을 봐야만 알 수 있습니다.
--
-- ============================================================================
--
--   대표님이 하실 일
