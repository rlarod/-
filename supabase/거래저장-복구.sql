-- =========================================================================
-- 청산 기록이 서버에 하나도 저장되지 않던 문제 — 원인과 해결
-- =========================================================================
-- 증상
--   '분명 수익 2천만원이었는데 -155 손실로 보인다'
--   새로고침하면 포지션·기록이 사라진다
--   서버 조회 결과: 전체거래수 0 인데 열린포지션 2
--
-- 원인
--   js/supabase-sync.js 는 청산 기록을 저장할 때 return_rate 컬럼을
--   함께 보냅니다(레버리지 미포함 일반 수익률).
--   그런데 trades 테이블에 그 컬럼이 없습니다.
--   컬럼 하나가 없으면 insert 전체가 거부되므로,
--   청산 기록이 단 한 건도 서버에 저장되지 않았습니다.
--
--   그래서 이런 일이 벌어집니다.
--     1) 거래해서 수익을 냄 -> 브라우저에만 남음
--     2) 새로고침 -> auth.js 가 서버에서 복원 시도
--     3) 서버 trades 가 비어 있음 -> 거래 기록 0건으로 복원
--     4) 실현손익 0 이 되고, 그 값이 다시 서버에 저장됨
--     5) 다시 거래하면 그 손익만 남음 (-155 처럼)
--
--   컬럼을 추가하는 패치 파일(schema-return-rate-patch.sql)이
--   있었지만 실행되지 않은 상태였습니다.
--
-- 이 파일은 컬럼을 추가하고, 제대로 됐는지 확인까지 합니다.
-- 기존 데이터는 건드리지 않습니다. 여러 번 실행해도 안전합니다.
-- =========================================================================


-- ---------------- 1) 없는 컬럼 추가 ----------------
alter table public.trades add column if not exists return_rate numeric;


-- ---------------- 2) 앞으로 같은 일이 없도록 ----------------
-- js/supabase-sync.js 가 보내는 컬럼이 전부 있는지 한 번에 확인합니다.
select
  needed.col                                        as 필요한컬럼,
  case when c.column_name is null then '❌ 없음 — 저장 실패함'
       else '✅ 있음' end                            as 상태
from (values
  ('user_id'), ('symbol'), ('side'), ('entry_price'), ('exit_price'),
  ('quantity'), ('leverage'), ('margin'), ('pnl'), ('roe'),
  ('return_rate'), ('fee'), ('close_reason'), ('created_at')
) as needed(col)
left join information_schema.columns c
  on c.table_schema = 'public'
 and c.table_name   = 'trades'
 and c.column_name  = needed.col
order by (c.column_name is null) desc, needed.col;


-- ---------------- 3) 현재 상태 ----------------
-- 이 SQL 을 돌린 뒤부터 거래하면 전체거래수가 늘어나야 정상입니다.
select
  (select count(*) from public.trades)            as 저장된_거래수,
  (select count(*) from public.positions)         as 열린포지션수,
  (select count(*) from public.trading_accounts)  as 계정수;


-- =========================================================================
-- 실행 후 확인 방법
-- =========================================================================
--   1) 사이트에서 로그인 -> 거래 한 번 진입하고 청산
--   2) 이 SQL 의 3번만 다시 실행
--   3) 저장된_거래수가 1 이상으로 늘어나면 해결된 것입니다
--
-- 이미 사라진 기록은 브라우저에만 있었기 때문에 되살릴 수 없습니다.
-- 다만 지금 이후의 거래는 정상적으로 서버에 쌓입니다.
