-- =========================================================================
-- check-stranded-orders.sql
--   ★좌초된 미체결 지정가 주문★ 이 지금 몇 건이고 얼마가 묶여 있는지 봅니다.
-- =========================================================================
-- ⛔ 이 파일은 읽기만 합니다. 아무것도 바뀌지 않습니다.
--    SELECT 만 들어 있습니다. INSERT · UPDATE · DELETE 가 한 줄도 없습니다.
--    실행해도 회원 데이터·잔고·랭킹은 하나도 달라지지 않습니다.
--
-- ── 무엇을 알아보려는 것인가 (2026-09-09, P1) ────────────────────────────
--   지정가 주문을 걸고 새로고침하면 화면에서 그 주문이 사라졌습니다.
--   증거금과 진입수수료는 이미 지갑에서 빠져나간 뒤라 그대로 사라집니다.
--
--       증거금 1,000 · 100배 → 명목 100,000 → 진입수수료 20 (메이커 0.02%)
--       지정가 걸기   지갑 -1,020, 총자산 표시는 그대로 (1,000 이 "묶인 증거금")
--       새로고침      지갑 -1,020, 총자산 표시 = 지갑        → -1,020 이 증발
--
--   ★되찾을 길이 없습니다.★ 체결 판정은 100% 브라우저 안에서만 돕니다
--   (서버에는 체결 엔진이 없습니다). 취소 단추는 미체결 카드 안에만 있는데
--   그 카드가 숨겨져 있어 누를 수도 없습니다.
--   그래서 서버 orders 행이 status='OPEN' 인 채로 영원히 남습니다.
--
--   ⚠ 서버 계급 자산(supabase/schema-rank-1000.sql:263 · :384)은 이 margin 을
--     자산으로 세고 있습니다. 즉 ★서버는 맞고 화면만 틀린★ 상태입니다.
--
--   지금 몇 명이 이 상태인지 아무도 모릅니다. health-check.sql 에도 이 조회가
--   없습니다. 그래서 이 파일을 따로 만들었습니다.
--
-- ── 어떻게 실행하나 ──────────────────────────────────────────────────────
--   Supabase SQL Editor 에 이 파일을 통째로 붙여넣고 Run 을 누르시면 됩니다.
--   블록이 3개(1번~3번)라 Editor 가 ★마지막 결과 하나만★ 보여 줍니다.
--   세 개를 다 보시려면 블록을 하나씩 드래그해서 선택한 뒤 Run 해 주세요.
--   급하시면 ★1번만★ 돌려도 됩니다. 그게 핵심입니다.
--
-- ── 결과를 어떻게 읽나 ───────────────────────────────────────────────────
--   1번 표가 ★비어 있으면 피해자가 없다★ 는 뜻입니다. 그게 제일 좋은 결과입니다.
--   줄이 있으면 그 회원의 '묶인_증거금' 이 화면에서 사라진 금액입니다.
--
--   ⚠ 이 조회만으로는 "지금도 살아 있는 정상 미체결" 과 "좌초된 것" 을
--     완전히 가르지는 못합니다. 브라우저를 켜 둔 채 주문을 걸어놓은 회원도
--     status='OPEN' 이기 때문입니다. 3번 블록의 '경과' 를 같이 보세요.
--     ★몇 시간~며칠이 지난 OPEN 은 사실상 전부 좌초된 것★ 입니다.
--
-- 회원 이름은 랭킹에도 그대로 나오는 닉네임만 씁니다.
-- =========================================================================


-- =========================================================================
-- 1번 - 회원별 요약  ★이것만 보셔도 됩니다★
-- =========================================================================
select p.nickname                                 as 회원,
       count(*)                                   as 좌초된_미체결_건수,
       round(sum(o.margin))                       as 묶인_증거금,
       round(sum(o.margin * o.leverage) * 0.0002) as 날아간_진입수수료,
       min(o.created_at)                          as 가장_오래된것
  from public.orders o
  join public.profiles p on p.id = o.user_id
 where o.status = 'OPEN' and o.order_type = 'limit'
 group by p.nickname
 order by 묶인_증거금 desc;


-- =========================================================================
-- 2번 - 전체 합계  (한 줄로 "우리 피해가 얼마인가")
-- =========================================================================
select count(distinct o.user_id)                  as 영향받은_회원수,
       count(*)                                   as 좌초된_주문_총건수,
       round(sum(o.margin))                       as 묶인_증거금_합계,
       round(sum(o.margin * o.leverage) * 0.0002) as 날아간_진입수수료_합계,
       round(sum(o.margin) + sum(o.margin * o.leverage) * 0.0002) as 사라진_돈_합계
  from public.orders o
 where o.status = 'OPEN' and o.order_type = 'limit';


-- =========================================================================
-- 3번 - 건별 상세  (오래된 것부터. 경과가 길수록 좌초가 확실합니다)
-- =========================================================================
select p.nickname                                  as 회원,
       o.symbol                                    as 종목,
       o.side                                      as 방향,
       o.price                                     as 지정가,
       round(o.margin)                             as 증거금,
       o.leverage                                  as 배율,
       round(o.margin * o.leverage)                as 명목,
       round(o.margin * o.leverage * 0.0002, 2)    as 진입수수료,
       o.created_at                                as 주문시각,
       date_trunc('minute', now() - o.created_at)  as 경과,
       case
         when now() - o.created_at > interval '1 day'  then '★거의 확실히 좌초★'
         when now() - o.created_at > interval '1 hour' then '좌초로 보임'
         else '아직 살아 있을 수 있음(브라우저를 켜 둔 상태)'
       end                                         as 판정
  from public.orders o
  join public.profiles p on p.id = o.user_id
 where o.status = 'OPEN' and o.order_type = 'limit'
 order by o.created_at asc;
