/* -------------------------------------------------------------------------
 * 선언들(SRC) — 소스에 있는 font-size 선언을 ★전부★ 뽑습니다.
 *
 * ⚠️ 값을 정규식으로 "숫자+px" 라고 미리 가정하지 않습니다. 그게 구멍의 원인이었습니다.
 *    `font-size:` 뒤부터 ★선언이 끝날 때까지★ 를 통째로 잘라옵니다.
 *    끝 = ; 또는 } 또는 줄바꿈. 단 괄호 안의 것은 세지 않습니다
 *    (clamp(11px, 2vw, 17px) 처럼 안에 쉼표·괄호가 있습니다).
 * ----------------------------------------------------------------------- */
function 선언들(SRC) {
  const 소스 = String(SRC == null ? "" : SRC);
  const 결과 = [];
  const re = /font-size\s*:/gi;
  let m;
  while ((m = re.exec(소스)) !== null) {
    const 시작 = m.index + m[0].length;
    let i = 시작;
    let 깊이 = 0;
    /* ⚠️ 2026-09-04 실측으로 갈래를 둘로 나눴습니다.
         (가) font-size:" + LIST_FONT + "px    ← 값이 ★따옴표로 시작★ = JS 로 붙이는 것.
                                                 따옴표를 만나도 계속 읽어야 합니다.
         (나) "font-size:13px",                ← 값이 숫자로 시작 = 따옴표가 곧 끝.
                                                 (js/symbol-stream-switch.js:776 이 이 모양입니다)
       한 갈래로 만들면 반드시 한쪽이 잘못 읽힙니다. */
    const 첫글자 = (/^\s*(.)/.exec(소스.slice(시작, 시작 + 40)) || [])[1] || "";
    const 붙이는값 = 첫글자 === '"' || 첫글자 === "'" || 첫글자 === "`";
    while (i < 소스.length) {
      const c = 소스.charAt(i);
      if (c === "(") 깊이++;
      else if (c === ")") {
        if (깊이 > 0) 깊이--;
      } else if (깊이 === 0 && (c === ";" || c === "}" || c === "\n" || c === "\r")) {
        break;
      } else if (깊이 === 0 && c === "/") {
        /* font-size 값에는 "/" 가 안 들어갑니다(그건 font 줄임표기입니다).
           주석 안의 산문 — "font-size:14px / padding:7px …" — 을 여기서 끊습니다.
           괄호 안(calc(17px/2))은 위 깊이 검사가 지켜 줍니다. */
        break;
      } else if (깊이 === 0 && !붙이는값 && (c === '"' || c === "'" || c === "`")) {
        break;
      }
      i++;
    }
    const 원문 = 소스.slice(시작, i);
    결과.push({
      원문: 원문.trim(),
      줄: 소스.slice(0, m.index).split("\n").length,
      자리: m.index,
    });
    re.lastIndex = i;
  }
  return 결과;
}

/* -------------------------------------------------------------------------
 * 판정(원문) — 값 하나가 어떤 종류인지 정합니다.
 *
 *   px       17px 처럼 px 로 딱 적은 것            (통과)
 *   영       단위 없는 0 — 글자를 숨기는 관용구      (통과)
 *   동적px   "..." + 상수 + "px" 로 붙이는 것       (통과 · 숫자는 다른 검사가 잽니다)
 *   동적모름 붙이는데 px 로 안 끝나는 것            (위반)
 *   금지     그 밖의 전부                          (위반)
 *   빈값     값이 비었음                           (위반)
 *
 * ★순서가 중요합니다.★ 함수를 동적보다 먼저 봅니다 —
 *   calc(" + A + "px + 2px)  는 따옴표가 있지만 calc 라서 금지여야 합니다.
 * ----------------------------------------------------------------------- */
function 판정(원문) {
  const 값 = String(원문 == null ? "" : 원문)
    .replace(/!\s*important/gi, "")
    .trim()
    .replace(/\s+/g, " ");

  if (값 === "") return { 종류: "빈값", 이유: "값이 비었습니다", 원문: 값 };

  /* 1) 함수부터 — 따옴표가 섞여 있어도 함수면 금지입니다 */
  const 함수 = /(^|[^A-Za-z0-9_-])(clamp|calc|min|max|var|attr|env)\s*\(/i.exec(값);
  if (함수) {
    const 이름 = 함수[2].toLowerCase();
    return { 종류: "금지", 이유: 함수이유[이름], 원문: 값 };
  }

  /* 2) px 로 딱 적은 것 — 이것만이 정답입니다 */
  if (/^\d+(?:\.\d+)?px$/i.test(값)) {
    return { 종류: "px", px: parseFloat(값), 원문: 값 };
  }

  /* 3) 단위 없는 0 — 글자를 숨기는 관용구 (머리말 참조) */
  if (/^0(?:\.0+)?$/.test(값)) return { 종류: "영", px: 0, 원문: 값 };

  /* 4) 이름으로 적은 값 */
  if (이름값.test(값)) {
    return { 종류: "금지", 이유: "이름으로 적은 값 — 몇 px 인지 알 수 없습니다", 원문: 값 };
  }

  /* 5) JS 로 붙이는 동적 값 */
  if (/["'`]/.test(값) || 값.indexOf("+") >= 0) {
    /* 따옴표·꼬리 쉼표를 떼고 마지막이 px 인지 봅니다.
       "font-size:" + F + "px",  처럼 배열 원소로 적힌 것도 있습니다. */
    const 벗김 = 값.replace(/["'`]/g, "").replace(/[,;\s]+$/, "").trim();
    if (/px$/i.test(벗김)) return { 종류: "동적px", 원문: 값 };
    return {
      종류: "동적모름",
      이유: "JS 로 붙이는데 px 로 안 끝납니다 — 단위를 px 로 고정하세요",
      원문: 값,
    };
  }

  /* 6) px 아닌 단위 */
  const u = /^[+-]?(?:\d+(?:\.\d+)?|\.\d+)\s*([A-Za-z%]+)$/.exec(값);
  if (u) {
    const 단위 = u[1].toLowerCase();
    return {
      종류: "금지",
      이유: 단위이유[단위] || 단위 + " — px 이 아닙니다. px 로 적으세요",
      원문: 값,
    };
  }

  /* 7) 그 밖 — 무엇이든 px 이 아니면 막습니다 (기본이 금지입니다) */
  return { 종류: "금지", 이유: "px 로 적은 값이 아닙니다", 원문: 값 };
}

/* -------------------------------------------------------------------------
 * 단위위반(SRC) — 소스에서 "px 로 안 적은" 선언만 뽑아 돌려줍니다.
 * 빈 배열이면 통과입니다.
 * ----------------------------------------------------------------------- */
function 단위위반(SRC) {
  return 선언들(SRC)
    .map(function (d) {
      const p = 판정(d.원문);
      p.줄 = d.줄;
      return p;
    })
    .filter(function (p) {
      return p.종류 !== "px" && p.종류 !== "영" && p.종류 !== "동적px";
    });
}

/* 사람이 읽을 한 줄로 만듭니다 */
function 요약(위반들) {
  if (!위반들 || !위반들.length) return "";
  return 위반들
    .map(function (v) {
      return (v.줄 ? v.줄 + "행 " : "") + "font-size:" + v.원문 + " → " + (v.이유 || v.종류);
    })
    .join(" / ");
}

