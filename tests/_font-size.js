function 자체검증() {
  const 놓친것 = 잡아야하는것.filter(function (s) {
    const t = 판정(s).종류;
    return t === "px" || t === "영" || t === "동적px";
  });
  const 헛잡은것 = 놓치면안되는것.filter(function (s) {
    const t = 판정(s).종류;
    return !(t === "px" || t === "영" || t === "동적px");
  });

  /* ⚠️ ★판정() 만 확인하면 안 됩니다.★
     2026-09-04 실측 — 단위위반() 을 `return []` 로 갈아치우는 돌연변이를 심었더니
     판정() 은 멀쩡해서 자체검증이 초록이었고, ★읽는 쪽 9개가 전부 통과했습니다.★
     그래서 뽑기 → 판정 → 거르기 를 통째로 한 번 태워 봅니다. */
  const 통짜 = [];
  if (단위위반('".x{font-size:1em;}"').length !== 1) 통짜.push("1em 을 안 잡음");
  if (단위위반('".x{font-size:clamp(11px, 2vw, 17px);}"').length !== 1) 통짜.push("clamp 를 안 잡음");
  if (단위위반('".x{font-size:17px;}"').length !== 0) 통짜.push("17px 을 헛잡음");
  if (선언들('".a{font-size:17px;} .b{font-size:18px;}"').length !== 2) 통짜.push("선언 뽑기가 헛돎");
  /* 마지막 기본값 갈래도 통짜로 한 번 밟습니다 (위 표본 주석 참조) */
  if (단위위반('".x{font-size:17;}"').length !== 1) 통짜.push("단위 없는 17 을 안 잡음");

  return {
    전부통과: 놓친것.length === 0 && 헛잡은것.length === 0 && 통짜.length === 0,
    통짜: 통짜,
    놓친것: 놓친것,
    헛잡은것: 헛잡은것,
    표본수: 잡아야하는것.length + 놓치면안되는것.length,
    설명:
      (통짜.length ? "통짜: " + 통짜.join(" · ") + " " : "") +
      (놓친것.length ? "못 잡음: " + 놓친것.join(" · ") + " " : "") +
      (헛잡은것.length ? "헛잡음: " + 헛잡은것.join(" · ") : ""),
  };
}

