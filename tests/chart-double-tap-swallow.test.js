/* tests/chart-double-tap-swallow.test.js
 * =========================================================================
 * "빠르게 두 번 톡 하면 아무 일도 안 일어난다" — 지금 이렇다는 기록 (2026-08-28)
 * =========================================================================
 * ⚠ 이 파일은 고장을 고치는 파일이 아닙니다. **고장이 있다는 것을 아는
 *   상태로 남겨 두는** 파일입니다. 나중에 누가 고치면 이 파일이 깨지면서
 *   "이제 고쳐졌다" 고 알려줍니다. 그때 이 파일을 지우거나 반대로 바꾸세요.
 *
 * ── 무슨 현상인가 ──────────────────────────────────────────────────────
 *   회원이 두 점을 빠르게 톡 톡 찍으면 선이 안 그어집니다. 오류도 안 뜨고
 *   화면도 멀쩡합니다. 회원은 "안 눌렸나" 하고 다시 찍습니다.
 *   전형적인 조용한 고장입니다.
 *
 * ── 차트팀 실측 (2026-08-28) ──────────────────────────────────────────
 *   톡 사이 간격 400ms  ->  안 그려짐
 *                550ms  ->  그려짐
 *                700ms  ->  그려짐
 *                900ms  ->  그려짐
 *   이미 나가 있는 추세선으로도 똑같이 재봤더니 400ms 에서 똑같이 실패했습니다.
 *   -> 이번에 여러선을 열면서 생긴 것이 아니라 **원래 있던 것**입니다.
 *
 * ── 원인 (우리 코드가 아닙니다) ───────────────────────────────────────
 *   lightweight-charts 가 0.5초 안의 두 번째 클릭을 더블클릭으로 보고
 *   subscribeClick 으로 안 넘깁니다. 우리 onClick 은 아예 불리지 않습니다.
 *   그래서 이 현상은 jsdom 으로 재현할 수 없습니다 — 우리 가짜 차트는
 *   subscribeClick 을 직접 부르기 때문에 언제나 성공합니다.
 *   **여기서 시간 간격을 흉내 내는 테스트를 쓰면 아무것도 안 지킵니다.**
 *   그래서 이 파일은 대신 "지금 상태" 세 가지를 못 박습니다.
 *
 * ── 그래서 무엇을 못 박나 ─────────────────────────────────────────────
 *   [1] 라이브러리 판이 5.2.0 에 묶여 있다
 *       판이 바뀌면 삼키는 시간도 바뀔 수 있습니다. 판을 올리는 사람이
 *       여기서 걸려 다시 재게 만드는 것이 이 검사의 목적입니다.
 *   [2] 톡으로 쓰는 도구가 전부 subscribeClick 한 길로만 들어온다
 *       그래서 다섯 도구가 한꺼번에 같은 영향을 받습니다.
 *   [3] 아직 우회 장치를 안 만들었다
 *       (dblclick 을 따로 듣거나, 톡 사이 시간을 재는 장치가 없습니다)
 *       누가 만들면 여기가 깨집니다 = "고쳐졌다" 는 신호입니다.
 *
 * ── PM 보고에 덧붙일 것 ───────────────────────────────────────────────
 *   PM 지시문에는 "추세선·피보나치·자·채널" 넷이라고 적혀 있었는데,
 *   코드를 직접 확인해 보니 **돋보기(zoom)도 같은 길**입니다. 다섯입니다.
 *   돋보기는 그림으로 안 남고 화면만 확대해서 눈에 덜 띌 뿐입니다.
 *
 * 파일만 읽습니다. 브라우저도 서버도 부르지 않습니다.
 * ========================================================================= */
"use strict";

const fs = require("fs");
const path = require("path");

const REPO = process.env.REPO || path.resolve(__dirname, "..");
const SRC = fs.readFileSync(path.join(REPO, "js", "chart-drawings.js"), "utf8");
const HTML = fs.readFileSync(path.join(REPO, "index.html"), "utf8");

let pass = 0;
let fail = 0;
const 실패목록 = [];

function ok(제목, 조건, 도움말) {
  if (조건) { pass++; console.log("  ✓ " + 제목); }
  else {
    fail++;
    실패목록.push(제목 + (도움말 ? " -> " + 도움말 : ""));
    console.log("  ✗ " + 제목 + (도움말 ? " -> " + 도움말 : ""));
  }
}
function 절(제목) { console.log("\n" + 제목); }

console.log("\n빠른 두 번 톡이 삼켜진다 — 지금 이렇다는 기록 (2026-08-28)");

/* =========================================================================
 * [1] 라이브러리 판이 묶여 있다
 * ========================================================================= */
절("[1] 차트 라이브러리 판이 5.2.0 에 묶여 있다");
{
  const m = HTML.match(/lightweight-charts@([0-9]+\.[0-9]+\.[0-9]+)/);
  ok("index.html 이 lightweight-charts 판을 못 박아 부른다 (latest 로 두면 어느 날 조용히 바뀝니다)",
    !!m, m ? m[1] : "판 번호가 없습니다");
  ok("지금 판이 5.2.0 이다 — 차트팀 실측(400ms 실패 / 550ms 성공)은 이 판에서 잰 것입니다",
    !!m && m[1] === "5.2.0",
    (m ? m[1] : "?") + " — 판을 올렸으면 400 / 550 / 700 / 900ms 를 다시 재고 이 파일을 고치세요");
  ok("판을 여러 곳에서 부르지 않는다 (두 판이 섞이면 어느 쪽 행동인지 못 가립니다)",
    (HTML.match(/lightweight-charts@/g) || []).length === 1,
    (HTML.match(/lightweight-charts@/g) || []).length + "곳");
}

/* =========================================================================
 * [2] 톡으로 쓰는 도구가 전부 한 길로만 들어온다
 * ========================================================================= */
절("[2] 톡 도구 다섯이 전부 subscribeClick 한 길이다");
{
  /* 우리 코드가 톡을 받는 입구는 chart.subscribeClick(onClick) 하나뿐입니다.
     그래서 라이브러리가 두 번째 톡을 삼키면 다섯 도구가 한꺼번에 영향을 받습니다.
     입구가 늘어나면(예: 캔버스 click 을 따로 듣기) 여기가 깨집니다 —
     그건 곧 우회 장치를 만들었다는 뜻이라 다시 재야 합니다. */
  ok("차트에 톡을 거는 자리가 딱 한 곳이다",
    (SRC.match(/chart\.subscribeClick\(/g) || []).length === 1,
    "지금 " + (SRC.match(/chart\.subscribeClick\(/g) || []).length + "곳");
  ok("그 한 곳이 onClick 을 건다", /chart\.subscribeClick\(onClick\)/.test(SRC));

  /* 영향을 받는 도구 목록을 이름으로 박아 둡니다 — 개수만 세면 도구가
     바뀌어도 숫자만 맞아 통과합니다. */
  const twoTap = (SRC.match(/var TWO_TAP = \{([^}]*)\}/) || [])[1] || "";
  const threeTap = (SRC.match(/var THREE_TAP = \{([^}]*)\}/) || [])[1] || "";
  const 이름들 = (twoTap + "," + threeTap).split(",")
    .map((s) => s.split(":")[0].trim()).filter(Boolean).sort().join(",");
  /* 2026-09-03 18차 — 사각형(rect)·화살표(arrow) 가 같은 길로 들어와 다섯 -> 일곱.
     둘 다 chart.subscribeClick 한 길만 씁니다(따로 만든 입구가 없습니다).
     그래서 라이브러리가 두 번째 톡을 삼키면 이 둘도 같이 영향을 받습니다. */
  ok("영향을 받는 도구가 추세선·피보나치·자·돋보기·여러선·사각형·화살표 일곱이다",
    이름들 === "arrow,channel,fib,rect,ruler,trend,zoom", 이름들);

  /* 브러시만 다른 길입니다 — 끌어서 긋기라 포인터를 직접 받습니다.
     그래서 브러시는 이 현상의 영향을 받지 않습니다. 이것도 같이 못 박습니다. */
  ok("브러시는 포인터를 직접 받는 다른 길이라 이 현상과 무관하다",
    /addEventListener\("pointerdown", onBrushDown, true\)/.test(SRC));
  ok("브러시는 톡 도구 목록에 없다", 이름들.indexOf("brush") === -1, 이름들);
}

/* =========================================================================
 * [3] 아직 우회 장치를 안 만들었다  ← 고치면 여기가 깨집니다
 * ========================================================================= */
절("[3] 아직 우회 장치가 없다 (만들면 이 절이 깨지고, 그게 '고쳐졌다' 는 신호입니다)");
{
  ok("dblclick 을 따로 듣지 않는다",
    SRC.indexOf("dblclick") === -1,
    "dblclick 을 듣기 시작했다면 우회 장치를 만든 것입니다 — 400ms 를 다시 재고 이 파일을 고치세요");
  /* 차트 칸 · 캔버스에 click 을 직접 거는 것만 봅니다.
     막대·칩의 버튼(b, b1, b2)에 거는 click 은 원래부터 있던 것이라 셈에서 뺍니다. */
  ok("차트 칸에 click 을 직접 걸지 않는다",
    !/container\.addEventListener\(\s*["']click["']/.test(SRC),
    "차트 칸의 click 을 직접 듣기 시작했다면 우회 장치입니다 — 다시 재고 이 파일을 고치세요");
  ok("캔버스에 click 을 직접 걸지 않는다",
    !/canvas\.addEventListener\(\s*["']click["']/.test(SRC),
    "캔버스 click 을 듣기 시작했다면 우회 장치입니다 — 다시 재고 이 파일을 고치세요");
  /* 2026-09-02 (13차) — 커서 도구의 "끌어 옮기기" 가 세 개를 더 걸었습니다.
     개수만 세면 무엇을 거는지 모릅니다. 그래서 이름까지 못 박습니다(더 센 기준입니다).
     톡(click) 쪽에 새 입구가 생기면 여기가 그대로 깨집니다. */
  const 입구 = [];
  const 입구RE = /container\.addEventListener\(\s*"([a-z]+)"\s*,\s*(\w+)/g;
  let 입구M;
  while ((입구M = 입구RE.exec(SRC))) 입구.push(입구M[1] + ":" + 입구M[2]);
  ok("차트 칸에 거는 것은 아래 넷뿐이다 (톡 쪽에 새 입구가 생기면 여기가 깨집니다)",
    입구.join(",") === [
      "pointerdown:onBrushDown",
      "pointerdown:onCursorDown",
      "pointermove:onCursorHover",
      "pointerleave:onCursorLeave"
    ].join(","),
    "지금 " + (입구.length ? 입구.join(", ") : "0곳"));
  ok("톡 사이 시간을 재는 장치가 없다",
    !/lastTap|lastClick|tapGap|TAP_MIN|TAP_GAP/.test(SRC),
    "톡 간격을 재기 시작했다면 우회 장치입니다 — 다시 재고 이 파일을 고치세요");
  ok("axisDoubleClickReset 을 따로 만지지 않는다 (더블클릭 쪽을 건드린 흔적)",
    (SRC.match(/axisDoubleClickReset/g) || []).length === 0,
    "지금 " + (SRC.match(/axisDoubleClickReset/g) || []).length + "곳");
}

/* =========================================================================
 * [4] 이 현상을 아는 사람이 남긴 기록이 여기 있다
 * -------------------------------------------------------------------------
 * 실측 숫자를 코드 주석이 아니라 이 파일에 둡니다 —
 * js/chart-drawings.js 는 차트팀 것이고, 기록팀은 tests/ 밖을 안 고칩니다.
 * ========================================================================= */
절("[4] 실측 숫자가 이 파일에 남아 있다");
{
  const 나 = fs.readFileSync(__filename, "utf8");
  [["400ms", "안 그려짐"], ["550ms", "그려짐"], ["700ms", "그려짐"], ["900ms", "그려짐"]]
    .forEach(function (p) {
      ok("실측 " + p[0] + " -> " + p[1] + " 이 적혀 있다",
        나.indexOf(p[0]) !== -1, "숫자를 지우지 마세요 — 다시 재야 하는 사람의 출발점입니다");
    });
  ok("이번에 생긴 것이 아니라 원래 있던 것이라고 적혀 있다", 나.indexOf("원래 있던 것") !== -1);
  ok("jsdom 으로는 재현할 수 없다는 이유가 적혀 있다", 나.indexOf("재현할 수 없습니다") !== -1);
  ok("고쳐지면 이 파일을 어떻게 하라고 적혀 있다", 나.indexOf("이제 고쳐졌다") !== -1);
}

/* =========================================================================
 * 끝
 * ========================================================================= */
console.log("\n  통과 " + pass + " / 실패 " + fail);
if (fail) {
  console.log("\n실패한 것");
  실패목록.forEach((s) => console.log("  - " + s));
}
process.exit(fail ? 1 : 0);
