"use strict";

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const REPO = process.env.REPO || path.resolve(__dirname, "..");
const TESTS = __dirname;
const 굵기 = require("./_font-weight.js");

const ESC = String.fromCharCode(27);
const MARK_OK = ESC + "[32m" + "✓" + ESC + "[0m";
const MARK_NG = ESC + "[31m" + "✗" + ESC + "[0m";

let 통과 = 0;
let 실패 = 0;
const 실패목록 = [];
function ok(제목, 조건, 도움말) {
  if (조건) {
    통과++;
    console.log("  " + MARK_OK + " " + 제목);
  } else {
    실패++;
    실패목록.push(제목 + (도움말 ? " → " + 도움말 : ""));
    console.log("  " + MARK_NG + " " + 제목 + (도움말 ? "\n      → " + 도움말 : ""));
  }
}
function 절(t) {
  console.log("\n" + t);
}

console.log("==========================================================");
console.log(" font-weight 굵기 판정기 — 단 하나의 출처 봉인");
console.log("==========================================================");

/* =========================================================================
 * [1] 출처 파일이 제자리에 있는가
 * ========================================================================= */
절("[1] tests/_font-weight.js 가 제자리에 있는가");
{
  const 경로 = path.join(TESTS, "_font-weight.js");
  ok("tests/_font-weight.js 가 있다", fs.existsSync(경로));

  /* ⚠️ 디스크에만 있고 git 밖이면 다른 PC 에서 npm test 가 죽습니다.
     (CLAUDE.md — "디스크엔 있는데 git 엔 없는 파일", 하루에 세 번 났습니다)
     ★git add 전에는 여기가 빨갛습니다. 그게 정상이고, 커밋 직전에 알려주는 것이 목적입니다.★ */
  let 추적 = "";
  try {
    추적 = execFileSync("git", ["-C", REPO, "ls-files", "tests/_font-weight.js"], {
      encoding: "utf8",
    }).trim();
  } catch (e) {
    추적 = "";
  }
  ok("git 이 tests/_font-weight.js 를 추적한다", 추적.length > 0,
    "아직 git 밖입니다 — order-panel.test.js 가 이 파일을 require 하므로, " +
    "이걸 빼고 커밋하면 다른 PC 에서 그 테스트가 통째로 죽습니다");

  const 위생 = fs.readFileSync(path.join(TESTS, "tests-dir-hygiene.test.js"), "utf8");
  ok("tests-dir-hygiene 의 도우미목록에 _font-weight.js 가 적혀 있다",
    위생.indexOf('"_font-weight.js"') >= 0,
    "안 적으면 커밋하는 순간 '정체불명 파일' 로 걸립니다");
}

/* =========================================================================
 * [2] 판정기가 표본을 다 맞추는가
 * ========================================================================= */
절("[2] 판정기 표본 — 잡아야 할 것 / 헛잡으면 안 되는 것");
{
  const 검 = 굵기.자체검증();
  ok("자체검증 표본 " + 검.표본수 + "개를 다 맞춘다", 검.전부통과, 검.설명);
  ok("표본이 40개 이상이다 (표본을 줄여서 통과시키지 않았다)", 검.표본수 >= 40,
    "지금 " + 검.표본수 + "개");

  /* ★표본에 없는 것으로 한 번 더★ — 표본 목록만 맞추도록 판정을 짜맞추면
     여기서 걸립니다. 아래는 _font-weight.js 의 표본에 안 들어 있는 값들입니다. */
  const 밖에서잡아야 = [
    "BOLD ER", "Lighter", "INHERIT", "Revert-Layer",
    "var(--tl-weight)", "calc(700)", "clamp(100,1vw,900)", "env(w)",
    "300 400", "900 1000", "600em", "700%", "0.5", "0", "-400", "1500",
    /* ⚠️ 아래는 ★어느 갈래에도 안 걸려 마지막 기본값(금지)까지 내려가는★ 값들입니다.
       2026-09-04 실측 — _font-size.js 를 만들 때 이런 표본이 하나도 없어서
       "기본값을 통과로 바꾸는" 돌연변이를 ★10개가 전부 놓쳤습니다.★
       앞 갈래만 밟는 표본은 기본값 갈래를 지키지 못합니다. */
    "굵게", "boldish", "70 0", "7,00", "700 ;", "n700",
  ];
  const 밖에서놓친것 = 밖에서잡아야.filter(function (s) {
    return 굵기.판정(s).종류 === "굵기";
  });
  ok("표본 밖의 " + 밖에서잡아야.length + "가지도 전부 잡는다",
    밖에서놓친것.length === 0, 밖에서놓친것.join(" · "));

  const 밖에서통과해야 = ["200", "300", "750", "999", "1000", "400 !important", "BOLD", "  normal  "];
  const 밖에서헛잡음 = 밖에서통과해야.filter(function (s) {
    return 굵기.판정(s).종류 !== "굵기";
  });
  ok("멀쩡한 굵기 표기 " + 밖에서통과해야.length + "가지를 헛잡지 않는다",
    밖에서헛잡음.length === 0, 밖에서헛잡음.join(" · "));

  /* ★얇은 쪽은 막지 않습니다★ — 이 판정기는 "몇인가" 만 답합니다.
     100 이 통과하는 것이 정상이고, 얼마까지 허용할지는 부르는 쪽 정책입니다. */
  ok("100 처럼 얇게 적어도 판정은 통과한다 (상한은 부르는 쪽이 정합니다)",
    굵기.판정("100").종류 === "굵기" && 굵기.판정("100").굵기 === 100);
}

/* =========================================================================
 * [3] 실제로 뚫렸던 구멍 — 옛 정규식 vs 새 판정
 * ========================================================================= */
절("[3] ★옛 정규식이 통과시키던 것을 새 판정이 잡는가★");
{
  /* 옛 방식을 여기 그대로 재현해 맞대어 봅니다.
     ⚠️ 진짜 파일은 안 건드립니다 — 아래는 전부 지어낸 문자열입니다. */
  const 옛 = function (블록) { return !/font-weight:(800|900)/.test(블록); };  /* true = 통과 */

  [
    ["font-weight: 800", "공백 하나 (가장 흔한 표기)"],
    ["font-weight:bolder", "bolder (부모 700 밑이면 900)"],
    ["font-weight:850", "850 (가변 글꼴)"],
    ["FONT-WEIGHT:900", "대문자"],
    ["font-weight:1000", "1000 (900 보다 굵음)"],
    ["font-weight :800", "콜론 앞 공백 (옛 정규식은 font-weight: 를 붙여서만 봅니다)"],
  ].forEach(function (쌍) {
    const 블록 = ".x{" + 쌍[0] + ";}";
    const 새로잡음 = 굵기.넘는것(블록, 700).length + 굵기.못판정(블록).length;
    ok("옛 검사는 " + 쌍[1] + " 을 통과시키고 새 판정은 잡는다",
      옛(블록) === true && 새로잡음 === 1,
      "옛통과=" + 옛(블록) + " 새잡음=" + 새로잡음);
  });

  /* 옛 검사가 잡던 것은 새 판정도 반드시 잡아야 합니다 (뒷걸음질 금지) */
  ok("옛 검사가 잡던 font-weight:800 은 새 판정도 잡는다",
    옛(".x{font-weight:800;}") === false &&
    굵기.넘는것(".x{font-weight:800;}", 700).length === 1);
  ok("옛 검사가 잡던 font-weight:900 은 새 판정도 잡는다",
    옛(".x{font-weight:900;}") === false &&
    굵기.넘는것(".x{font-weight:900;}", 700).length === 1);

  /* 반대 방향 구멍 — 주석 산문을 값으로 읽어 ★거짓 실패★ 를 내던 것 */
  {
    const 주석블록 = "/* 예전에는 font-weight:800 을 썼습니다 */\n.x{font-weight:700;}";
    ok("옛 검사는 주석 안의 800 때문에 ★거짓 실패★ 를 낸다",
      옛(주석블록) === false);
    ok("★새 판정은 주석을 떼고 봐서 거짓 실패를 안 낸다★",
      굵기.넘는것(주석블록, 700).length === 0 && 굵기.못판정(주석블록).length === 0,
      굵기.요약(굵기.못판정(주석블록)));
  }

  /* @font-face 함정 — 범위 표기를 요소 굵기로 읽으면 헛잡습니다 */
  {
    const 글꼴 = "@font-face{font-family:'X';font-weight:500 600;src:url(a.woff2);}";
    ok("@font-face 의 범위 표기(500 600)를 요소 굵기로 안 읽는다",
      굵기.선언들(글꼴).length === 0 && 굵기.못판정(글꼴).length === 0);
    const 섞임 = 글꼴 + "\n.x{font-weight:800;}";
    ok("@font-face 를 빼면서 바깥 규칙까지 같이 지우지 않는다",
      굵기.넘는것(섞임, 700).length === 1,
      굵기.요약(굵기.넘는것(섞임, 700)));
  }

  /* 판정기를 통째로 무력화하는 방향 — 아무것도 안 잡게 만들면 걸립니다 */
  ok("판정기가 최소한 하나는 잡는다 (전부 통과시키는 판정이 아니다)",
    굵기.못판정(".x{font-weight:bolder;}").length === 1);
}

/* =========================================================================
 * [4] 봐주는 것이 늘지 않았는가
 * ========================================================================= */
절("[4] 이름값 중 봐주는 것은 normal·bold 둘뿐이다");
{
  /* CSS 가 숫자를 못 박아 둔 둘만 환산합니다. 부모와 무관해서 확정이 됩니다. */
  ok("normal 은 400 으로 환산한다", 굵기.판정("normal").굵기 === 400);
  ok("bold 는 700 으로 환산한다", 굵기.판정("bold").굵기 === 700);
  ok("bold 는 상한 700 을 안 넘는다 (환산이 맞아야 상한 검사가 안 뒤집힙니다)",
    굵기.넘는것(".x{font-weight:bold;}", 700).length === 0);
  ok("bold 는 상한 600 에서는 잡힌다 (환산이 진짜로 쓰인다)",
    굵기.넘는것(".x{font-weight:bold;}", 600).length === 1);

  /* 부모에 따라 달라지는 것은 환산하지 않고 막습니다 — 판단 근거는 머리말 */
  ["bolder", "lighter", "inherit", "initial", "unset", "revert", "revert-layer"]
    .forEach(function (v) {
      ok(v + " 는 환산하지 않고 막는다 (부모에 따라 달라집니다)",
        굵기.판정(v).종류 === "금지");
    });
  ok("bolder 를 막는 이유가 판정기 안에 글로 적혀 있다",
    /부모/.test(굵기.판정("bolder").이유 || ""),
    "이유가 없으면 다음 사람이 '왜 못 쓰지' 로 읽고 그냥 예외를 엽니다");

  /* ★파일 이름별 예외를 못 만들게★ — 판정 함수가 인자를 하나만 받습니다.
     예외 목록은 반드시 자랍니다(tests-dir-hygiene 이 같은 이유로 이름을 바꿨습니다). */
  ok("판정() 이 값 하나만 받는다 (파일별 예외를 넣을 자리가 없다)",
    굵기.판정.length === 1, "인자 " + 굵기.판정.length + "개");
  ok("못판정() 이 소스 하나만 받는다", 굵기.못판정.length === 1,
    "인자 " + 굵기.못판정.length + "개");

  /* 빈 값도 통과시키지 않습니다 */
  ok("font-weight: 만 적고 값이 없으면 잡는다",
    굵기.못판정(".x{font-weight:;}").length === 1);
}

/* =========================================================================
 * [5] 상한(정책)이 판정기 안으로 스며들지 않았는가
 *     "몇 굵기인가" 는 판정기, "얼마까지 허용" 은 봉인 쪽 정책입니다.
 *     여기가 무너지면 화면마다 다른 정책이 도우미 안에 눌러앉습니다.
 * ========================================================================= */
절("[5] 상한은 부르는 쪽이 정한다 (판정기 안에 숫자를 박지 않았다)");
{
  ok("넘는것() 이 상한을 인자로 받는다", 굵기.넘는것.length === 2,
    "인자 " + 굵기.넘는것.length + "개 — 상한이 인자가 아니면 도우미 안에 박힌 것입니다");
  ok("상한 700 과 900 이 서로 다른 답을 낸다 (인자가 진짜로 쓰인다)",
    굵기.넘는것(".x{font-weight:800;}", 700).length === 1 &&
    굵기.넘는것(".x{font-weight:800;}", 900).length === 0);

  const 원본 = fs.readFileSync(path.join(TESTS, "_font-weight.js"), "utf8");
  const 판정기 = 원본.replace(/\/\*[^]*?\*\//g, "");
  ok("판정기 코드에 700·800·900 을 기본 상한으로 박아두지 않았다",
    !/상한\s*=\s*\d/.test(판정기) && !/천장\s*=\s*(700|800|900)\b/.test(판정기),
    "상한을 도우미 안에 박으면 화면마다 다른 정책을 못 씁니다");
}

/* =========================================================================
 * [6] 읽는 쪽이 진짜로 이 출처를 부르는가
 * ========================================================================= */
절("[6] 읽는 쪽이 이 출처를 실제로 읽는가");
{
  /* ⚠️ 이름을 여기 적어두는 것이 곧 "이 봉인은 굵기 방어가 있다" 는 선언입니다.
     누가 그 파일에서 절을 지우면 그 자리에서 빨개집니다.
     ★읽는 쪽이 늘면 여기에 이름을 추가하세요.★ */
  const 읽는쪽 = ["order-panel.test.js"];
  읽는쪽.forEach(function (이름) {
    const p = path.join(TESTS, 이름);
    if (!fs.existsSync(p)) {
      ok(이름 + " 가 있다", false, "파일이 없습니다");
      return;
    }
    const s = fs.readFileSync(p, "utf8");
    ok(이름 + " 가 판정기를 부른다 (require · 넘는것 · 못판정 · 자체검증)",
      s.indexOf('require("./_font-weight.js")') >= 0 &&
        s.indexOf("넘는것(") >= 0 &&
        s.indexOf("못판정(") >= 0 &&
        s.indexOf("자체검증()") >= 0,
      "require=" + (s.indexOf('require("./_font-weight.js")') >= 0) +
        " 넘는것=" + (s.indexOf("넘는것(") >= 0) +
        " 못판정=" + (s.indexOf("못판정(") >= 0) +
        " 자체검증=" + (s.indexOf("자체검증()") >= 0) +
        " — 넷 다 있어야 합니다. 자체검증() 이 빠지면 판정기가 헐거워져도 모릅니다");
  });

  /* ★옛 정규식이 되살아나지 않았는가★ — 판정기를 두고도 옆에 정규식을 다시
     적으면 그게 곧 두 벌입니다(확정 팔레트의 "두 벌 금지" 와 같은 생각).
     주석 안의 인용은 봐줍니다 — 이 건의 기록으로 일부러 남겨 둔 것입니다. */
  {
    const s = fs.readFileSync(path.join(TESTS, "order-panel.test.js"), "utf8");
    const 코드 = s.replace(/\/\*[^]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    ok("order-panel.test.js 코드에 옛 정규식이 되살아나지 않았다",
      !/font-weight:\(800\|900\)/.test(코드),
      "판정기를 두고 정규식을 다시 적으면 두 벌이 됩니다");
  }
}

/* =========================================================================
 * [7] 판정기가 문자열만 보는가
 * ========================================================================= */
절("[7] 판정기가 파일·네트워크를 안 읽는가");
{
  const 원본 = fs.readFileSync(path.join(TESTS, "_font-weight.js"), "utf8");
  /* ⚠️ ★주석을 먼저 떼고 봅니다.★ 머리말에 쓰는 법으로 require(...) 를
     적어 두었기 때문에, 주석째로 보면 ★거짓 실패★ 가 납니다.
     2026-09-04 에 기록팀이 같은 함정을 두 번 밟았습니다
     (주석 때문에 거짓 통과 / 주석 때문에 거짓 실패). 원인은 하나 —
     코드를 본다면서 주석을 같이 읽은 것입니다. */
  const 판정기 = 원본.replace(/\/\*[^]*?\*\//g, "");
  ok("주석을 떼고도 코드가 남아 있다 (검사가 헛돌지 않았다)", 판정기.length > 1500,
    "주석 뗀 뒤 " + 판정기.length + "자");
  ok("require() 를 쓰지 않는다", !/\brequire\s*\(/.test(판정기),
    "도우미가 딴 파일을 읽기 시작하면 무엇을 재는지 알 수 없어집니다");
  ok("파일을 읽지 않는다", !/readFileSync\s*\(|readdirSync\s*\(/.test(판정기));
  ok("네트워크를 부르지 않는다", !/\bfetch\s*\(|https?:\/\//.test(판정기));
  ok("사이트 코드를 실행하지 않는다", !/\beval\s*\(|new Function/.test(판정기));
  ok("머리말에 ★bolder 를 왜 환산하지 않는지★ 가 적혀 있다",
    원본.indexOf("환산이 안 됩니다") >= 0,
    "다음 사람이 '왜 bolder 를 숫자로 바꿔서 재지 않지' 로 읽습니다");
  ok("머리말에 @font-face 를 왜 빼는지가 적혀 있다",
    원본.indexOf("@font-face") >= 0 && 원본.indexOf("범위") >= 0);
}

