"use strict";

const fs = require("fs");
const path = require("path");

const REPO = path.join(__dirname, "..");
const SQL_DIR = path.join(REPO, "supabase");
const ESC = String.fromCharCode(27);
const MARK_OK = ESC + "[32m" + "✓" + ESC + "[0m";
const MARK_NG = ESC + "[31m" + "✗" + ESC + "[0m";

let pass = 0, fail = 0;
function ok(name, cond, detail) {
  if (cond) { pass++; console.log("  " + MARK_OK + " " + name); }
  else { fail++; console.log("  " + MARK_NG + " " + name + (detail ? " — " + detail : "")); }
}
function section(t) { console.log("\n" + t); }

const RT_PATH = path.join(SQL_DIR, "schema-tl-realtime.sql");
const RT = fs.readFileSync(RT_PATH, "utf8");

/* 주석을 지운 "실제로 실행되는 본문" */
function strip(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n").map((l) => l.replace(/--.*$/, "")).join("\n");
}

console.log("\nTL 지급 공식 — 옛것으로 되돌아가지 않는다");

/* =========================================================================
 * [1] 계수를 SQL 에서 읽어온다 (베껴 적지 않는다)
 * ========================================================================= */
section("[1] 계수를 SQL 파일에서 읽어왔다");

/* 옛 공식 — schema-tl-realtime.sql 8절 보정 지급 안에 원문 그대로 살아 있습니다.
   (보정은 "옛 공식으로 받았을 금액보다 줄지 않게" 채워 주는 용도라 필요합니다) */
const 옛구간 = (function () {
  const i = strip(RT).indexOf("legacy :=");
  return i < 0 ? "" : strip(RT).slice(i, i + 700);
})();
ok("보정 지급 안의 옛 공식 구간을 찾았다", 옛구간.length > 200, String(옛구간.length));

const 건당 = (/count\(\*\)\s*from\s*public\.trades[^)]*\)[^*]*\)\s*,\s*0\)\s*\*\s*(\d+)/.exec(옛구간) ||
  /trades\s+t\s+where\s+t\.user_id\s*=\s*r\.uid\),\s*0\)\s*\*\s*(\d+)/.exec(옛구간) || [])[1];
const 수익률당 = (/from public\.trading_accounts ta[\s\S]{0,120}?\)\)\s*\*\s*(\d+)/.exec(옛구간) || [])[1];
ok("옛 공식: 거래 1건당 배점을 읽었다 = " + 건당, Number(건당) === 10, "읽은 값 " + 건당);
ok("옛 공식: 수익률 1%당 배점을 읽었다 = " + 수익률당, Number(수익률당) === 20, "읽은 값 " + 수익률당);
ok("옛 공식에 계급보너스(rank_points)가 더해진다",
  /profiles pr2 where pr2\.id = r\.uid\), 0\)/.test(옛구간));

/* 새 공식 — 3절 tl_total_amount() */
const 새구간 = (function () {
  const s = strip(RT);
  const i = s.indexOf("function public.tl_total_amount");
  return i < 0 ? "" : s.slice(i, i + 500);
})();
const m새 = /floor\(round\((\d+)\s*\*\s*log\(2,\s*\(1\s*\+\s*greatest\(0,[\s\S]*?\/\s*(\d+)\)/.exec(새구간);
const m참여 = /least\((\d+),\s*public\.tl_total_days\(p_uid\)\s*\*\s*(\d+)\)/.exec(새구간);
ok("새 공식 구간을 찾았다", 새구간.length > 100, String(새구간.length));
ok("새 공식: 성과 배점을 읽었다 = " + (m새 && m새[1]), !!m새 && Number(m새[1]) === 300);
ok("새 공식: 기준 금액을 읽었다 = " + (m새 && m새[2]), !!m새 && Number(m새[2]) === 10000000);
ok("새 공식: 참여 상한을 읽었다 = " + (m참여 && m참여[1]), !!m참여 && Number(m참여[1]) === 150);
ok("새 공식: 하루당 참여 TL 을 읽었다 = " + (m참여 && m참여[2]), !!m참여 && Number(m참여[2]) === 5);

/* 읽어온 계수로 두 공식을 그대로 세웁니다. */
const C = {
  건당: Number(건당), 수익률당: Number(수익률당),
  성과배점: m새 ? Number(m새[1]) : NaN, 기준금액: m새 ? Number(m새[2]) : NaN,
  참여상한: m참여 ? Number(m참여[1]) : NaN, 하루참여: m참여 ? Number(m참여[2]) : NaN,
};

/* 옛 공식 — 거래 건수 × 10 + max(0, 수익률%) × 20 + 계급보너스 */
function 옛공식(거래건수, 수익률퍼센트, 계급보너스) {
  return 거래건수 * C.건당 + Math.max(0, 수익률퍼센트) * C.수익률당 + (계급보너스 || 0);
}
/* 새 공식 — floor(300 × log2(1 + max(0,누적순수익)/1,000만)) + min(150, 거래날짜수 × 5) */
function 새공식(누적순수익, 거래날짜수) {
  const 성과 = Math.floor(C.성과배점 * Math.log2(1 + Math.max(0, 누적순수익) / C.기준금액));
  return 성과 + Math.min(C.참여상한, (거래날짜수 || 0) * C.하루참여);
}

/* =========================================================================
 * [2] 김갱님 실측 검산 — 2억을 잃고도 70 TL
 * ========================================================================= */
section("[2] 2026-08-25 서버 실측 검산 (김갱님)");
{
  /* 서버에 살아 있던 값: 거래 7건 / 확정손익 약 -2억 / 계급보너스 0 / 보유 TL 70 */
  const 거래건수 = 7;
  const 초기자금 = 100000;          // js/trading.js INITIAL_BALANCE
  const 확정손익 = -200000000;      // 약 2억 손실
  const 수익률 = (확정손익 / 초기자금) * 100;

  ok("수익률이 음수다", 수익률 < 0, String(수익률) + "%");
  ok("옛 공식으로 계산하면 정확히 70 TL 이다", 옛공식(거래건수, 수익률, 0) === 70,
    "서버 실측 보유 TL 70 과 맞아야 합니다. 계산값 " + 옛공식(거래건수, 수익률, 0));
  ok("2억을 잃었는데도 TL 이 0 이 아니다(이것이 문제다)", 옛공식(거래건수, 수익률, 0) > 0);
  ok("손실이 10배로 커져도 옛 공식 TL 은 그대로 70 이다",
    옛공식(거래건수, (확정손익 * 10 / 초기자금) * 100, 0) === 70,
    "옛 공식은 손실을 전혀 반영하지 않습니다");
  ok("거래를 3배 더 하면 옛 공식 TL 도 3배가 된다(손해와 무관)",
    옛공식(거래건수 * 3, 수익률, 0) === 210);

  /* 같은 회원을 새 공식으로 계산하면 성과 몫은 0 입니다. */
  const 새성과 = 새공식(확정손익, 0);
  ok("새 공식에서는 성과 몫이 0 이다(손실이면 안 준다)", 새성과 === 0, String(새성과));
  ok("새 공식은 음수 TL 을 주지 않는다", 새공식(확정손익, 0) >= 0);
  ok("새 공식에서 참여 몫은 거래한 '날짜 수' 로만 붙는다",
    새공식(확정손익, 1) === C.하루참여 && 새공식(확정손익, 100) === C.참여상한,
    "1일=" + 새공식(확정손익, 1) + " / 100일=" + 새공식(확정손익, 100));
}

/* =========================================================================
 * [3] 익절·손절 반복 — 옛 공식은 무한, 새 공식은 멈춘다
 * ========================================================================= */
section("[3] 익절·손절 반복으로 긁을 수 있는가");
{
  /* +1,000만 / -1,000만 을 200번씩 = 400건. 누적 순수익은 정확히 0 입니다. */
  const 회 = 200;
  const 건수 = 회 * 2;
  const 누적순수익 = 0;

  const 옛 = 옛공식(건수, 0, 0);
  const 새 = 새공식(누적순수익, 1);
  ok("400건을 반복하면 옛 공식은 " + 옛 + " TL 이 쌓인다", 옛 === 건수 * C.건당, String(옛));
  ok("같은 거래를 새 공식으로 보면 성과 0 + 참여뿐이다", 새 === C.하루참여, String(새));
  ok("옛 공식이 새 공식보다 " + Math.round(옛 / 새) + "배 더 준다", 옛 / 새 >= 100);
  ok("마켓 최고가(500 TL) 상품을 옛 공식으로는 거래만 반복해 살 수 있다", 옛 >= 500,
    "이게 되면 아이템 경제가 무너집니다");
  ok("새 공식으로는 같은 반복으로 500 TL 에 못 미친다", 새 < 500, String(새));

  /* 거래를 더 반복해도 새 공식은 상한에서 멈춥니다. */
  ok("반복을 10배로 늘려도 새 공식은 참여 상한 " + C.참여상한 + " 을 못 넘는다",
    새공식(0, 99999) === C.참여상한);
  ok("반복을 10배로 늘리면 옛 공식은 그대로 10배가 된다",
    옛공식(건수 * 10, 0, 0) === 옛 * 10);
}

