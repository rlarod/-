/* =========================================================================
 * [7] supabase/수익기록-복구.sql 봉인 — 손실이 지워지면 TL 이 부풀어 오른다
 * ========================================================================= */
section("[7] 수익기록-복구.sql 이 봉인된 채로 있다");
{
  /* ── 2026-08-25 조사 확정 (본부장이 서버에서 직접 검산) ────────────────
   * realized_pnl 과 sum(trades.pnl) 이 다른 것은 고장이 아니라 설계입니다.
   *     trades.pnl   = 총손익 − 청산수수료          (진입수수료가 안 빠짐)
   *     realized_pnl = 거기서 진입수수료까지 뺀 값   ← 진짜 잃은 돈
   *   김갱 실측: 손익합계 -147,053 + 진입수수료 52,947 = -200,000 = 서버값 ✓
   *
   * supabase/수익기록-복구.sql 은  realized_pnl = sum(trades.pnl)  로 덮습니다.
   * 돌리면 김갱님 손실 52,947 이 사라집니다. 되돌릴 수 없습니다.
   *
   * 왜 이 파일(TL 지급 공식)에서 같이 지키나 —
   *   옛 TL 공식이 realized_pnl 을 직접 씁니다.
   *       max(0, realized_pnl / initial_balance × 100) × 20
   *   손실이 지워지면 수익률이 올라가고 TL 과 랭킹이 같이 부풀어 오릅니다.
   *   즉 이 봉인이 풀리는 것은 "지급 공식이 조용히 바뀌는 것" 과 같은 일입니다.
   * ------------------------------------------------------------------- */
  const 복구경로 = path.join(SQL_DIR, "수익기록-복구.sql");
  ok("supabase/수익기록-복구.sql 이 기록으로 남아 있다(지우지 않았다)",
    fs.existsSync(복구경로));

  const 복구 = fs.existsSync(복구경로) ? fs.readFileSync(복구경로, "utf8") : "";
  const 복구live = strip(복구);

  ok("맨 앞에 실행 금지 표시가 있다",
    /⛔\s+이 파일을 실행하지 마십시오\.\s+\(2026-08-25 봉인\)/.test(복구),
    "이 줄이 사라지면 다음 사람이 그냥 Run 을 누릅니다");
  ok("금지 표시가 파일 맨 위 10줄 안에 있다",
    복구.split("\n").slice(0, 10).join("\n").indexOf("이 파일을 실행하지 마십시오") >= 0,
    "아래쪽에 있으면 못 보고 지나갑니다");

  /* 실제로 값을 바꾸는 문장이 살아 있으면 안 됩니다. */
  ok("실행되는 UPDATE 가 없다", !/\bupdate\s+public\.trading_accounts\b/i.test(복구live),
    "주석이 풀리면 회원 손실 기록이 덮어씌워집니다");
  ok("실행되는 DELETE / TRUNCATE 도 없다",
    !/\bdelete\s+from\b/i.test(복구live) && !/\btruncate\b/i.test(복구live));
  ok("실행되는 문장은 읽기(select)뿐이다",
    복구live.split(";").map((x) => x.trim()).filter(Boolean).every((x) => /^select\b/i.test(x)),
    "읽기 말고 다른 게 있으면 파일을 여는 것만으로 값이 바뀝니다");

  /* 옛 원문은 기록으로 남겨 둡니다 — 왜 안 되는지 다음 사람이 볼 수 있게. */
  ok("덮어쓰던 원문이 주석으로 보존돼 있다",
    /--\s*set realized_pnl = sub\.total,/.test(복구),
    "지우지 말고 남겨야 다음 사람이 같은 판단을 다시 안 합니다");
  ok("왜 봉인했는지 적혀 있다(진입수수료 차이)",
    /진입수수료가 안 빠짐/.test(복구) && /진입수수료까지 뺀 값/.test(복구));
  ok("김갱님 실측 검산이 숫자 그대로 남아 있다",
    /-147,053/.test(복구) && /52,947/.test(복구) && /-200,000/.test(복구),
    "숫자가 있어야 다음 사람이 직접 검산해 볼 수 있습니다");
  ok("돌리면 얼마가 사라지는지 적혀 있다", /손실 52,947 이 사라집니다/.test(복구));
  ok("되돌릴 수 없다고 알린다", /되돌릴 수 없습니다/.test(복구));

  /* 실측 검산이 실제로 맞는지 여기서 다시 더해 봅니다. */
  ok("손익합계 -147,053 + 진입수수료 52,947 = -200,000 이 맞다",
    -147053 - 52947 === -200000);

  /* 같은 오진을 하는 진단 파일도 같이 경고돼 있어야 합니다. */
  ok("diagnose-pnl.sql 이 같은 오진을 한다는 경고가 있다",
    /diagnose-pnl\.sql/.test(복구) && /무시하십시오/.test(복구),
    "그 파일은 '차이 0 = 정상' 으로 봐서 볼 때마다 '복구 필요' 라고 나옵니다");
  ok("supabase/diagnose-pnl.sql 도 읽기 전용이다",
    !/\bupdate\s|\bdelete\s+from\b|\btruncate\b/i.test(
      strip(fs.readFileSync(path.join(SQL_DIR, "diagnose-pnl.sql"), "utf8"))),
    "오진하는 파일이 값까지 바꾸면 최악입니다");

  /* 옛 TL 공식이 realized_pnl 을 쓴다는 사실 자체를 못 박습니다.
     이게 사실이라서 위 봉인이 TL 문제이기도 합니다. */
  ok("옛 TL 공식이 realized_pnl 을 직접 쓴다(그래서 봉인이 TL 문제다)",
    /ta\.realized_pnl \/ ta\.initial_balance/.test(옛구간));
  {
    /* 봉인이 풀렸을 때 TL 이 실제로 얼마나 부풀어 오르는지 숫자로 남깁니다.
       수익 구간 회원은 진입수수료만큼 수익률이 올라가 TL 이 그대로 늘어납니다. */
    const 초기자금 = 100000;              // js/trading.js INITIAL_BALANCE
    const 진짜 = 2000000;                 // 진입수수료까지 뺀 값
    const 부풀린 = 진짜 + 52947;          // 복구 파일이 덮어쓴 뒤
    const before = 옛공식(7, (진짜 / 초기자금) * 100, 0);
    const after = 옛공식(7, (부풀린 / 초기자금) * 100, 0);
    /* 소수점 오차가 있으므로 0.01 안쪽이면 같은 값으로 봅니다. */
    const 늘어난TL = after - before;
    ok("수익 회원이면 봉인이 풀리는 순간 옛 공식 TL 이 약 " + Math.round(늘어난TL) + " 늘어난다",
      Math.abs(늘어난TL - (52947 / 초기자금 * 100 * 20)) < 0.01,
      "before " + before + " / after " + after);
    ok("김갱님처럼 손실이면 옛 공식 TL 은 70 그대로다(그래도 랭킹 자산은 올라간다)",
      옛공식(7, ((-200000 + 52947) / 초기자금) * 100, 0) === 70);
  }
}

