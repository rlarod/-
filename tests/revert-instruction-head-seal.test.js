/* tests/revert-instruction-head-seal.test.js
 * =========================================================================
 * 봉인 — 되돌리기 안내에 ★상대 위치(HEAD 물결)★ 를 쓰지 않는다
 * =========================================================================
 * 2026-09-07 기록팀. PM 배정 3건. 감사팀이 커밋 32건에서 찾은 것을 못 박습니다.
 *
 * ── 무엇이 문제인가 ─────────────────────────────────────────────────────
 *   되돌리기 안내에 이렇게 적힌 것이 커밋 32건 있었습니다.
 *
 *       git checkout <HEAD 물결 1> -- <파일>
 *
 *   "HEAD 물결 1" 은 ★지금 HEAD 의 하나 앞★ 입니다. 그 안내를 적은 날에는 맞지만,
 *   뒤에 커밋이 쌓이면 ★엉뚱한 커밋★ 을 가리킵니다. 10건 뒤에 누르면 10건 전 판이
 *   아니라 "지금 기준 하나 앞" 이 나옵니다.
 *
 *   ⚠️ ★오류가 안 납니다.★ 종료코드 0 · git status 깨끗 · 파일도 그대로 있습니다.
 *      되돌린 줄 알고 넘어갑니다 — 전형적인 조용한 고장입니다.
 *      게다가 되돌리는 순간은 대개 ★사고 직후★ 라 제일 나쁜 때입니다.
 *
 *   고정된 것을 적어야 합니다 —  git checkout <그 커밋 해시>~1 -- <파일>
 *   해시는 커밋이 아무리 쌓여도 안 움직입니다.
 *
 * ── ⚠️ 지난 커밋 메시지는 안 봅니다 ──────────────────────────────────────
 *   git log 를 훑으면 이미 배포된 32건이 그 자리에서 빨개져, ★켜자마자 끄고 싶은
 *   봉인★ 이 됩니다. 커밋 메시지는 고칠 수도 없습니다.
 *   그래서 ★앞으로 쓰는 자리★ 만 봅니다 — 소스 파일 머리글과 tests/_order.txt.
 *
 * ── ⚠️ 이 파일 자신은 훑지 않습니다 ─────────────────────────────────────
 *   여기 설명 글자에 그 형태가 잔뜩 들어 있습니다. 자기 글자에 걸리면 켜자마자
 *   빨갛습니다. __filename 을 목록에서 뺍니다.
 *   ⚠️ 남의 파일에 ★설명용으로★ 써야 하면 아래 [탈출표] 를 쓰세요.
 *
 * ── ★2026-09-07 실측★ ───────────────────────────────────────────────────
 *   훑는 자리 전체에서
 *       HEAD 물결/캐럿을 쓰는 git 명령        0건   → 앞으로도 0
 *       되돌리기 안내 줄의 맨몸 HEAD 물결      0건   → 앞으로도 0
 *       git checkout HEAD -- (물결 없음)      3곳   → 아래 [알려진곳] 참조
 *
 *   ⚠️ 물결이 없는 "git checkout HEAD -- <파일>" 도 ★아무것도 안 되돌립니다.★
 *      이미 커밋된 뒤라면 HEAD 에 고쳐진 판이 들어 있으니까요.
 *      2026-09-07 에 별도 worktree 에서 실제로 눌러 확인했습니다 —
 *      js/trade-events-chat.js 를 안내대로 되돌렸더니 종료코드 0,
 *      md5 ff7816b5… 그대로, git status 깨끗. ★한 글자도 안 바뀌었습니다.★
 *      (올바른 안내 69db042~1 로 꺼내니 그 봉인이 10건 빨개졌습니다)
 *
 *      3곳 중 2곳은 ★사이트 코드(js/ · style.css)라 기록팀이 못 고칩니다.★
 *      이름을 적어 두고 PM 에게 올렸습니다. 나머지 1곳(tests/)은 오늘 고쳤습니다.
 *
 * ── 검사 ────────────────────────────────────────────────────────────────
 *   [0] 파서가 진짜로 걷었나 (표식)
 *   [1] HEAD 물결/캐럿을 쓰는 git 명령이 0건이다
 *   [2] 되돌리기 안내 줄에 맨몸 HEAD 물결이 0건이다
 *   [3] "git checkout HEAD --" 가 알려진 곳 밖에서 안 늘어난다 (래칫 · 줄면 통과)
 *   [4] ★돌연변이 자체검증★ — 사본에 심어 진짜 잡는지 · 자기 함정
 *   [5] 이 파일 자신
 *
 * ── 되돌리는 방법 ───────────────────────────────────────────────────────
 *   tests/_order.txt 의 등록 줄과 이 파일을 git rm -f 로 삭제합니다.
 *   (rm 은 디스크에서만 지워 git 에 남습니다 — tests-dir-hygiene 이 터집니다)
 *   ⚠️ 새로 만든 파일이라 git rm 이 맞습니다. 되돌릴 커밋 해시가 필요 없습니다.
 * =========================================================================
 */

var fs = require("fs");
var path = require("path");

const REPO = process.env.REPO || path.resolve(__dirname, "..");

var 통과 = 0;
var 실패 = 0;
var 실패목록 = [];

function ok(이름, 조건, 힌트) {
  if (조건) {
    통과++;
    console.log("  OK   " + 이름);
  } else {
    실패++;
    실패목록.push(이름 + (힌트 ? "  — " + 힌트 : ""));
    console.log("  FAIL " + 이름 + (힌트 ? "\n         → " + 힌트 : ""));
  }
}
function section(제목) {
  console.log("\n[" + 제목 + "]");
}

/* =======================================================================
 * [탈출표] 설명용으로 그 형태를 써야 할 때
 *
 *   그 줄에 아래 글자를 같이 적으면 봉인이 건너뜁니다.
 *   "안내가 아니라 설명" 이라는 뜻을 사람에게도 알려주는 표식입니다.
 * ===================================================================== */
var 탈출표 = "설명용·안내아님";

/* 상대 위치를 가리키는 말 — HEAD 뒤에 물결(~) 이나 캐럿(^) 이 붙은 것.
   ⚠️ 글자를 이어 붙여 만듭니다. 그래야 ★이 줄 자체가★ 잡히지 않습니다. */
var 상대 = new RegExp("HE" + "AD" + "\\s*[~^]");
var 깃명령 = /git\s+(checkout|restore|revert|reset|show|diff|log)\b/;
/* "git checkout HEAD -- <파일>" — 물결이 없어도 아무것도 안 되돌아갑니다 */
var 안되돌아감 = new RegExp("git\\s+checkout\\s+HE" + "AD\\s+--\\s+\\S");

/* =======================================================================
 * 훑을 자리 — ★앞으로 되돌리기 안내를 쓰는 곳★ 만.
 * 지난 커밋 메시지(git log)는 안 봅니다.
 * ===================================================================== */
function 대상파일() {
  var 목록 = ["tests/_order.txt", "style.css", "index.html"];

  ["js", "tests"].forEach(function (d) {
    fs.readdirSync(path.join(REPO, d)).forEach(function (f) {
      if (f.slice(-3) === ".js") 목록.push(d + "/" + f);
    });
  });
  fs.readdirSync(path.join(REPO, "css")).forEach(function (f) {
    if (f.slice(-4) === ".css") 목록.push("css/" + f);
  });
  if (fs.existsSync(path.join(REPO, "supabase"))) {
    fs.readdirSync(path.join(REPO, "supabase")).forEach(function (f) {
      if (f.slice(-4) === ".sql") 목록.push("supabase/" + f);
    });
  }

  /* ★이 파일 자신은 뺍니다★ — 설명 글자에 그 형태가 들어 있습니다 */
  var 나 = "tests/" + path.basename(__filename);
  return 목록.filter(function (f) { return f !== 나; });
}

/* =======================================================================
 * 판정기 — ★파일을 안 읽고 글자 배열만 받습니다.★ 그래야 [4] 에서 사본으로 돕니다.
 * ===================================================================== */
function 재기(글자들) {
  var 상대쓴곳 = [];      /* git 명령에 HEAD 물결 */
  var 안내맨몸 = [];      /* "되돌리" 가 있는 줄에 맨몸 HEAD 물결 */
  var 안되는곳 = [];      /* git checkout HEAD -- (물결 없음) */
  var 되돌리줄 = 0;       /* 표식 — "되돌리" 가 들어간 줄 수 */

  글자들.forEach(function (항) {
    String(항.글자).split(/\r?\n/).forEach(function (줄, i) {
      var 자리 = 항.이름 + ":" + (i + 1) + "  " + 줄.trim().slice(0, 78);
      if (줄.indexOf("되돌리") >= 0) 되돌리줄++;
      if (줄.indexOf(탈출표) >= 0) return;   /* [탈출표] — 설명용은 건너뜁니다 */

      var 물결 = 상대.test(줄);
      if (물결 && 깃명령.test(줄)) { 상대쓴곳.push(자리); return; }
      if (물결 && 줄.indexOf("되돌리") >= 0) { 안내맨몸.push(자리); return; }
      if (안되돌아감.test(줄)) 안되는곳.push(자리);
    });
  });

  return {
    상대쓴곳: 상대쓴곳,
    안내맨몸: 안내맨몸,
    안되는곳: 안되는곳,
    되돌리줄: 되돌리줄
  };
}

/* ===================================================================== */
console.log("=== 되돌리기 안내 — 상대 위치(HEAD 물결) 금지 봉인 ===");

var 파일들 = 대상파일().map(function (f) {
  return { 이름: f, 글자: fs.readFileSync(path.join(REPO, f), "utf8") };
});
var 잰것 = 재기(파일들);

/* ★[알려진곳]★ — 2026-09-07 실측. "git checkout HEAD -- " 가 남아 있는 곳.
   ⚠️ js/ 와 style.css 는 ★사이트 코드라 기록팀이 못 고칩니다.★ PM 에게 올렸습니다.
   고쳐지면 이 목록에서 지우세요 (줄어드는 것은 실패가 아닙니다). */
var 알려진곳 = ["js/trade-events-chat.js", "style.css"];

/* ---------------------------------------------------------------------
 * [0] 표식 — 파서가 눈이 먼 채 초록이 되는 것을 막습니다
 * ------------------------------------------------------------------- */
section("[0] 파서가 진짜로 걷었나");
{
  ok("훑을 파일을 모았다 (" + 파일들.length + "개)", 파일들.length >= 150,
    "150개 밑이면 목록 만드는 곳이 망가졌습니다. 그러면 아무 데도 안 보고 초록이 됩니다");
  ok("되돌리기 안내를 실제로 찾았다 (" + 잰것.되돌리줄 + "줄)", 잰것.되돌리줄 >= 100,
    "'되돌리' 가 들어간 줄이 100줄 밑이면 파일을 제대로 안 읽고 있는 것입니다");
  ok("이 파일 자신은 목록에서 뺐다",
    !대상파일().some(function (f) { return f.indexOf(path.basename(__filename)) >= 0; }),
    "안 빼면 여기 설명 글자에 걸려 켜자마자 빨갛습니다");
  ok("tests/_order.txt 를 훑는다",
    파일들.some(function (f) { return f.이름 === "tests/_order.txt"; }),
    "되돌리기 안내가 제일 많이 적히는 자리입니다");
}

/* ---------------------------------------------------------------------
 * [1] HEAD 물결을 쓰는 git 명령
 * ------------------------------------------------------------------- */
section("[1] 상대 위치를 가리키는 git 명령이 없다");
{
  ok("HEAD 뒤에 물결·캐럿을 붙인 git 명령이 0건이다 (지금 " + 잰것.상대쓴곳.length + "건)",
    잰것.상대쓴곳.length === 0,
    "상대 위치는 커밋이 쌓이면 ★엉뚱한 곳★ 을 가리킵니다. 오류가 안 나서 되돌린 줄 압니다.\n         " +
    "고정된 해시로 적으세요 —  git checkout <그 커밋 해시>~1 -- <파일>\n         " +
    "설명용으로 써야 하면 그 줄에 " + 탈출표 + " 를 같이 적으세요.\n         " +
    잰것.상대쓴곳.join("\n         "));
}

/* ---------------------------------------------------------------------
 * [2] 되돌리기 안내 줄의 맨몸 HEAD 물결
 * ------------------------------------------------------------------- */
section("[2] 되돌리기 안내 줄에 맨몸 상대 위치가 없다");
{
  ok("'되돌리' 가 적힌 줄에 상대 위치가 0건이다 (지금 " + 잰것.안내맨몸.length + "건)",
    잰것.안내맨몸.length === 0,
    "git 명령을 안 붙이고 '되돌리기: 하나 앞 판으로' 처럼 적어도 같은 병입니다.\n         " +
    잰것.안내맨몸.join("\n         "));
}

/* ---------------------------------------------------------------------
 * [3] "git checkout HEAD --" 래칫
 * ------------------------------------------------------------------- */
section("[3] 아무것도 안 되돌아가는 형태가 안 늘어난다 (래칫 · 줄면 통과)");
{
  var 새것 = 잰것.안되는곳.filter(function (자리) {
    return !알려진곳.some(function (a) { return 자리.indexOf(a + ":") === 0; });
  });
  ok("알려진 곳 밖에서 0건이다 (전체 " + 잰것.안되는곳.length + "곳 · 새것 " + 새것.length + "곳)",
    새것.length === 0,
    "'git checkout HEAD -- <파일>' 은 이미 커밋된 뒤라면 ★아무것도 안 되돌립니다.★\n         " +
    "2026-09-07 에 실제로 눌러 확인했습니다 (종료코드 0 · md5 그대로 · git status 깨끗).\n         " +
    "고친 커밋 해시를 찾아  git checkout <해시>~1 -- <파일>  로 적으세요.\n         " +
    새것.join("\n         "));

  /* ⚠️ ★줄어든 것은 실패로 만들지 않습니다.★ 사이트 코드라 수리팀이 언제 고칠지
     모르고, 고친 날 봉인이 빨개지면 안 됩니다. 안내만 찍습니다. */
  var 남은 = 알려진곳.filter(function (a) {
    return 잰것.안되는곳.some(function (자리) { return 자리.indexOf(a + ":") === 0; });
  });
  if (남은.length < 알려진곳.length) {
    console.log("  안내  알려진 곳 " + (알려진곳.length - 남은.length) + "곳이 고쳐졌습니다.");
    console.log("        이 파일의 알려진곳 을 " + JSON.stringify(남은) +
      " 로 줄여 적으면 되돌아가는 것까지 막힙니다. (실패는 아닙니다)");
  }
}

/* ---------------------------------------------------------------------
 * [4] ★돌연변이 자체검증★ — 사본 글자로만. 진짜 파일은 안 건드립니다.
 * ------------------------------------------------------------------- */
section("[4] 돌연변이 자체검증 (사본 글자로만 · 진짜 파일은 안 건드립니다)");
{
  /* ⚠️ 아래 문자열은 ★이어 붙여★ 만듭니다. 통째로 적으면 이 파일이 잡힙니다
     (지금은 자기 파일을 목록에서 빼지만, 남이 이 방식을 베낄 때를 위해서입니다). */
  var H = "HE" + "AD";

  var 가 = 재기([{ 이름: "사본.js", 글자: " * 되돌리기: git checkout " + H + "~1 -- js/무엇.js\n" }]);
  ok("(가) 상대 위치를 심으면 잡는다", 가.상대쓴곳.length === 1, JSON.stringify(가));

  var 나 = 재기([{ 이름: "사본.js", 글자: " * 되돌리기: git checkout " + H + "^ -- js/무엇.js\n" }]);
  ok("(나) 캐럿(^) 도 잡는다", 나.상대쓴곳.length === 1, JSON.stringify(나));

  var 다 = 재기([{ 이름: "사본.txt", 글자: "# 되돌리기: " + H + "~2 의 판으로 되돌립니다\n" }]);
  ok("(다) git 명령을 안 붙여도 되돌리기 줄이면 잡는다", 다.안내맨몸.length === 1,
    JSON.stringify(다));

  /* ★반대 확인★ — 고정된 해시는 통과해야 합니다. 이게 걸리면 옳은 안내가 막힙니다 */
  var 라 = 재기([{ 이름: "사본.js", 글자: " * 되돌리기: git checkout 69db042~1 -- js/무엇.js\n" }]);
  ok("(라) <해시>~1 은 통과한다 (자기 함정)",
    라.상대쓴곳.length === 0 && 라.안내맨몸.length === 0 && 라.안되는곳.length === 0,
    "고정 해시까지 막으면 쓸 수 있는 안내가 없어집니다. " + JSON.stringify(라));

  /* ★반대 확인★ — 40자리 전체 해시도 통과해야 합니다 */
  var 마 = 재기([{
    이름: "사본.js",
    글자: " * 되돌리기: git checkout 69db0421234567890abcdef1234567890abcdef12~1 -- x.js\n"
  }]);
  ok("(마) 40자리 전체 해시도 통과한다 (자기 함정)", 마.상대쓴곳.length === 0,
    JSON.stringify(마));

  /* ★반대 확인★ — git rm 안내(새 파일)는 아무 데도 안 걸려야 합니다 */
  var 바 = 재기([{
    이름: "사본.js",
    글자: " * 되돌리는 방법: 이 줄과 tests/무엇.test.js 를 git rm -f 로 삭제합니다\n"
  }]);
  ok("(바) git rm -f 안내는 안 걸린다 (자기 함정)",
    바.상대쓴곳.length === 0 && 바.안내맨몸.length === 0 && 바.안되는곳.length === 0,
    JSON.stringify(바));

  /* [탈출표] — 설명용은 건너뛴다. 설명을 못 쓰게 하면 다음 사람이 왜 금지인지 모릅니다 */
  var 사 = 재기([{
    이름: "사본.js",
    글자: " * 나쁜 예: git checkout " + H + "~1 -- x.js   (" + 탈출표 + ")\n"
  }]);
  ok("(사) [탈출표] 를 적은 설명 줄은 건너뛴다",
    사.상대쓴곳.length === 0 && 사.안내맨몸.length === 0,
    "설명을 막으면 다음 사람이 왜 금지인지 알 수 없습니다. " + JSON.stringify(사));

  /* 물결 없는 checkout HEAD */
  var 아 = 재기([{ 이름: "사본.js", 글자: " * 되돌리기: git checkout " + H + " -- js/무엇.js\n" }]);
  ok("(아) 물결 없는 'git checkout " + H + " --' 도 센다", 아.안되는곳.length === 1,
    "이것도 아무것도 안 되돌립니다. " + JSON.stringify(아));

  /* ★반대 확인★ — 이 파일 자신을 넣으면 잡히는가 (목록에서 빼는 이유의 근거) */
  var 자 = 재기([{ 이름: "사본.js", 글자: fs.readFileSync(__filename, "utf8") }]);
  ok("(자) 이 파일을 훑으면 자기 설명 글자에 걸린다 (그래서 뺍니다)",
    자.상대쓴곳.length + 자.안내맨몸.length + 자.안되는곳.length > 0,
    "안 걸린다면 [0] 의 '자기 파일 빼기' 가 이제 필요 없다는 뜻입니다. " +
    "상대 " + 자.상대쓴곳.length + " / 맨몸 " + 자.안내맨몸.length +
    " / 안되는곳 " + 자.안되는곳.length);
}

