/* -------------------------------------------------------------------------
 * @font-face{...} 구간의 [시작,끝) 자리를 모읍니다.
 *
 * ⚠️ @font-face 의 font-weight 는 ★글꼴 파일이 담당하는 범위★ 라 뜻이 다릅니다.
 *    style.css 20행이 실제로 `font-weight:500 600;` (범위)입니다.
 *    요소 굵기로 읽으면 헛잡으므로 통째로 뺍니다. 머리말 참조.
 * ----------------------------------------------------------------------- */
function 글꼴선언구간(소스) {
  const 구간 = [];
  const re = /@font-face\s*\{/gi;
  let m;
  while ((m = re.exec(소스)) !== null) {
    let i = m.index + m[0].length;
    let 깊이 = 1;
    while (i < 소스.length && 깊이 > 0) {
      const c = 소스.charAt(i);
      if (c === "{") 깊이++;
      else if (c === "}") 깊이--;
      i++;
    }
    구간.push([m.index, i]);
    re.lastIndex = i;
  }
  return 구간;
}

/* -------------------------------------------------------------------------
 * 선언들(SRC) — 소스에 있는 font-weight 선언을 ★전부★ 뽑습니다.
 *
 * ⚠️ 값을 "숫자" 라고 미리 가정하지 않습니다. 그게 구멍의 원인이었습니다.
 *    `font-weight:` 뒤부터 ★선언이 끝날 때까지★ 를 통째로 잘라옵니다.
 *    끝 = ; 또는 } 또는 줄바꿈 또는 / — 단 괄호 안의 것은 세지 않습니다.
 *    (`/` 로 끊는 이유는 tests/_font-size.js 와 같습니다 — 주석 산문에서
 *     "font-weight:700 / padding:4px" 처럼 이어 적는 일이 있습니다.
 *     굵기 값 자리에는 `/` 가 들어가지 않습니다.)
 * ----------------------------------------------------------------------- */
function 선언들(SRC) {
  /* ★주석을 먼저 뗍니다.★ 주문창 블록은 주석으로 잘라낸 구간이라 주석이 통째로
     들어 있습니다. 주석의 산문("예전에는 font-weight:800 을 썼습니다")을 값으로
     읽으면 ★코드는 멀쩡한데 검사가 빨개집니다.★ 머리말의 "반대 방향 구멍" 참조.
     ⚠️ 글자 수를 유지해야 줄 번호가 안 어긋나므로 ★같은 길이의 공백★ 으로 바꿉니다
        (줄바꿈은 그대로 둡니다). 지우면 "몇 행" 이 전부 밀립니다. */
  const 소스 = String(SRC == null ? "" : SRC)
    .replace(/\/\*[\s\S]*?\*\//g, function (m) { return m.replace(/[^\n]/g, " "); });
  const 뺄구간 = 글꼴선언구간(소스);
  const 결과 = [];
  const re = /font-weight\s*:/gi;
  let m;
  while ((m = re.exec(소스)) !== null) {
    const 시작 = m.index + m[0].length;
    let i = 시작;
    let 깊이 = 0;
    /* 값이 따옴표로 시작하면 JS 로 붙이는 것입니다 — 따옴표를 만나도 계속 읽습니다.
       (tests/_font-size.js 가 2026-09-04 실측으로 갈래를 나눈 것과 같은 이유) */
    const 첫글자 = (/^\s*(.)/.exec(소스.slice(시작, 시작 + 40)) || [])[1] || "";
    const 붙이는값 = 첫글자 === '"' || 첫글자 === "'" || 첫글자 === "`";
    while (i < 소스.length) {
      const c = 소스.charAt(i);
      if (c === "(") 깊이++;
      else if (c === ")") {
        if (깊이 > 0) 깊이--;
      } else if (깊이 === 0 && (c === ";" || c === "}" || c === "\n" || c === "\r" || c === "/")) {
        break;
      } else if (깊이 === 0 && !붙이는값 && (c === '"' || c === "'" || c === "`")) {
        break;
      }
      i++;
    }
    const 자리 = m.index;
    const 글꼴안 = 뺄구간.some(function (r) { return 자리 >= r[0] && 자리 < r[1]; });
    if (!글꼴안) {
      결과.push({
        원문: 소스.slice(시작, i).trim(),
        줄: 소스.slice(0, 자리).split("\n").length,
        자리: 자리,
      });
    }
    re.lastIndex = i;
  }
  return 결과;
}

/* -------------------------------------------------------------------------
 * 판정(원문) — 값 하나가 몇 굵기인지 정합니다.
 *
 *   굵기   숫자로 확정됨 (.굵기 에 숫자가 들어 있습니다)   → 잴 수 있음
 *   금지   숫자로 확정 못 함                              → 위반
 *   빈값   값이 비었음                                    → 위반
 *
 * ★순서가 중요합니다.★ 함수를 먼저 봅니다 — calc(400 + 300) 안에 숫자가
 *   들어 있어서 숫자 검사를 먼저 하면 잘못 통과할 수 있습니다.
 * ----------------------------------------------------------------------- */
function 판정(원문) {
  const 값 = String(원문 == null ? "" : 원문)
    .replace(/!\s*important/gi, "")
    .trim()
    .replace(/\s+/g, " ");

  if (값 === "") return { 종류: "빈값", 이유: "값이 비었습니다", 원문: 값 };

  /* 1) 함수부터 — 안에 숫자가 있어도 금지입니다 */
  const 함수 = /(^|[^A-Za-z0-9_-])(var|calc|clamp|min|max|attr|env)\s*\(/i.exec(값);
  if (함수) {
    const 이름 = 함수[2].toLowerCase();
    return { 종류: "금지", 이유: 함수이유[이름], 원문: 값 };
  }

  /* 2) 숫자 — CSS 규격상 1 ~ 1000 입니다. 가변 글꼴은 850 같은 값도 씁니다 */
  if (/^\d+(?:\.\d+)?$/.test(값)) {
    const n = parseFloat(값);
    if (n >= 1 && n <= 1000) return { 종류: "굵기", 굵기: n, 원문: 값 };
    return {
      종류: "금지",
      이유: n + " — font-weight 는 1 ~ 1000 입니다. 이 값은 브라우저가 무시합니다",
      원문: 값,
    };
  }

  /* 3) CSS 가 숫자를 못 박아 둔 이름값 둘 (normal=400 · bold=700) */
  const 소문자 = 값.toLowerCase();
  if (Object.prototype.hasOwnProperty.call(이름숫자, 소문자)) {
    return { 종류: "굵기", 굵기: 이름숫자[소문자], 원문: 값, 이름값: true };
  }

  /* 4) 부모에 따라 달라지는 이름값 — 머리말의 판단 근거 참조 */
  if (Object.prototype.hasOwnProperty.call(상대이유, 소문자)) {
    return { 종류: "금지", 이유: 상대이유[소문자], 원문: 값 };
  }

  /* 5) JS 로 붙이는 값 — 굵기는 단위가 없어서 ★끝만 봐서는 확정이 안 됩니다★.
        (글씨 크기는 "…+px" 로 단위라도 확정할 수 있었지만 여기는 그것도 없습니다) */
  if (/["'`]/.test(값) || 값.indexOf("+") >= 0) {
    return {
      종류: "금지",
      이유: "JS 로 붙이는 값 — 몇 굵기인지 여기서 못 잽니다. 숫자로 적으세요",
      원문: 값,
    };
  }

  /* 6) 그 밖 — 무엇이든 숫자로 확정 못 하면 막습니다 (기본이 금지입니다).
        `500 600` 같은 범위 표기, `700px` 처럼 단위가 붙은 것,
        `\s*700` 같은 정규식 조각이 전부 여기로 옵니다. */
  return { 종류: "금지", 이유: "숫자로 확정할 수 없는 굵기 표기입니다", 원문: 값 };
}

/* -------------------------------------------------------------------------
 * 값들(SRC) — 선언 전부에 판정을 붙여 돌려줍니다
 * ----------------------------------------------------------------------- */
function 값들(SRC) {
  return 선언들(SRC).map(function (d) {
    const p = 판정(d.원문);
    p.줄 = d.줄;
    return p;
  });
}

/* 숫자로 확정 못 한 것만 (빈 배열이면 통과) */
function 못판정(SRC) {
  return 값들(SRC).filter(function (p) { return p.종류 !== "굵기"; });
}

/* 상한을 넘는 것만 (빈 배열이면 통과). ★상한은 부르는 쪽이 정합니다★ */
function 넘는것(SRC, 상한) {
  const 천장 = Number(상한);
  return 값들(SRC).filter(function (p) {
    return p.종류 === "굵기" && p.굵기 > 천장;
  });
}

/* 사람이 읽을 한 줄로 만듭니다 */
function 요약(목록) {
  if (!목록 || !목록.length) return "";
  return 목록
    .map(function (v) {
      return (v.줄 ? v.줄 + "행 " : "") + "font-weight:" + v.원문 +
        " → " + (v.이유 || (v.종류 === "굵기" ? "굵기 " + v.굵기 : v.종류));
    })
    .join(" / ");
}

