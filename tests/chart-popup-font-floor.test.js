절("[4] ★칩 줄 접기 기준이 칩 글씨와 같이 움직였는가★");
{
  /* 칩 줄 높이는 글씨 크기에 딸려 있습니다.
       11px 시절  1줄 23px · 2줄 49px · 3줄 76px    -> FOLD_LINE 30 / 56
       17px 지금  1줄 31.5px · 2줄 67px · 3줄 102.5px -> FOLD_LINE 40 / 80
     글씨만 키우고 기준을 두면 ★뜻이 조용히 달라집니다★ —
     2026-09-03 실측: 기준을 안 옮겼을 때 1440 기본 9칩(2줄 67px > 56)이
     ★처음부터 접힌 채★ 떴습니다. 회원은 칩 대신 "▾ 지표 9" 만 봅니다.
     오류도 안 나고 화면도 멀쩡합니다 — 이 프로젝트가 P1 로 부르는 "조용한 고장". */
  const IND = 소스["js/chart-indicators.js"];
  const 칩 = 글씨크기(IND, ".tl-ind-btn");
  const m1 = /FOLD_LINE1\s*=\s*(\d+(?:\.\d+)?)/.exec(IND);
  const m2 = /FOLD_LINE2\s*=\s*(\d+(?:\.\d+)?)/.exec(IND);
  ok("FOLD_LINE1 · FOLD_LINE2 를 찾았다", !!(m1 && m2), "이름이 바뀌었습니다");

  if (칩 && m1 && m2) {
    const L1 = Number(m1[1]), L2 = Number(m2[1]);
    /* 칩 한 줄 높이 = 글씨 x 1.5(line-height) + 위아래 여백 4 + 테두리 2 */
    const 한줄 = 칩 * 1.5 + 4 + 2;
    const 두줄 = 한줄 * 2 + 4;   /* 줄 사이 gap 4px */
    const 세줄 = 한줄 * 3 + 8;

    ok("FOLD_LINE1 이 한 줄(" + 한줄 + "px)보다 크다 — 한 줄이면 접기 단추를 안 그린다",
      L1 > 한줄, "FOLD_LINE1=" + L1);
    ok("FOLD_LINE1 이 두 줄(" + 두줄 + "px)보다 작다 — 두 줄이면 접기 단추를 보여준다",
      L1 < 두줄, "FOLD_LINE1=" + L1);
    ok("FOLD_LINE2 가 두 줄(" + 두줄 + "px) 이상이다 — ★두 줄까지는 안 접는다★",
      L2 >= 두줄, "FOLD_LINE2=" + L2);
    ok("FOLD_LINE2 가 세 줄(" + 세줄 + "px)보다 작다 — ★세 줄부터 접는다★",
      L2 < 세줄, "FOLD_LINE2=" + L2);
  }

  /* 접기 단추 글씨가 옆 칩과 같아야 합니다 — 단추만 작으면 그게 다시 작은 글씨입니다 */
  const 접기 = 글씨크기(IND, ".tl-ind-fold");
  ok("접기 단추 글씨가 옆 칩과 같다", 칩 !== null && 접기 === 칩,
    "칩 " + 칩 + "px / 접기 " + 접기 + "px");
}

