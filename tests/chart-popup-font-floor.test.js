절("[1] 16곳이 전부 " + 바닥 + "px 이상인가");
{
  자리.forEach(([f, sel, 무엇]) => {
    const v = 글씨크기(소스[f], sel);
    ok(무엇 + " (" + f.replace("js/", "") + " " + sel.replace("\" + NOTE_ID + \"", "{알림줄}") + ")",
      v !== null && v >= 바닥,
      v === null ? "선택자를 못 찾았습니다 — 이름이 바뀌었나요?" : "지금 " + v + "px");
  });

  /* 좁은 폭 전용 리플레이 두 줄은 @media 안이라 위 방법으로 못 집습니다.
     media 블록만 잘라서 그 안의 font-size 를 전부 봅니다. */
  const RP = 소스["js/chart-replay.js"];
  const mi = RP.indexOf("@media (max-width:560px)");
  ok("리플레이 좁은 폭 @media 블록을 찾았다", mi >= 0, "블록 이름이 바뀌었습니다");
  if (mi >= 0) {
    const 블록 = RP.slice(mi, RP.indexOf("}\",", mi) + 3);
    const 값들 = (블록.match(/font-size:\s*(\d+(?:\.\d+)?)px/g) || [])
      .map((s) => Number(/(\d+(?:\.\d+)?)/.exec(s)[1]));
    ok("리플레이 좁은 폭 @media 안에 글씨가 2개 이상 있다", 값들.length >= 2, "찾은 값: " + 값들.join(","));
    /* ⚠️ 이 블록에는 배정 밖인 .tl-rp-lock .s(16px) 가 섞여 있습니다 — 위 [2] 참조.
       배정받은 것은 .tl-rp-hint · .tl-rp-banner 두 줄이라 그 둘만 이름으로 봅니다. */
    [".tl-rp-hint", ".tl-rp-banner"].forEach((sel) => {
      const v = 글씨크기(블록, " " + sel);
      ok("리플레이 좁은 폭 " + sel + " 글씨가 " + 바닥 + "px 이상이다",
        v !== null && v >= 바닥,
        v === null ? "못 찾았습니다" : "지금 " + v + "px");
    });
  }
}

