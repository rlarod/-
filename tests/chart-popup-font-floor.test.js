절("[5] 돌연변이 자체검증 — 이 검사가 진짜 잡는가");
{
  /* 실제 파일은 안 건드립니다. 글자만 바꿔서 검사 함수에 먹입니다. */
  const 가짜작게 = '".tl-kit-btn{color:#838DA4;font-size:11px;font-weight:600;}"';
  ok("11px 로 되돌리면 [1] 이 빨개진다",
    글씨크기(가짜작게, ".tl-kit-btn") < 바닥,
    "안 잡혔습니다 — 검사가 헛돕니다");

  const 가짜크게 = '".tl-kit-btn{color:#838DA4;font-size:20px;font-weight:600;}"';
  ok("더 키우면 [1] 이 안 빨개진다 (바닥이지 천장이 아니다)",
    글씨크기(가짜크게, ".tl-kit-btn") >= 바닥,
    "천장처럼 굴고 있습니다 — 대표가 더 키우라고 할 때마다 이 파일을 고쳐야 합니다");

  const 가짜미디어 = '"@media (max-width:560px){ .tl-rp-hint{font-size:13px;} }"';
  ok("@media 안에서 줄이면 [3] 이 빨개진다",
    /@media[^{]*max-width[^]{0,1200}?font-size:\s*(?:[0-9]|1[0-5])px/.test(가짜미디어),
    "안 잡혔습니다 — 지난 세 번의 실패 경로가 다시 열려 있습니다");

  ok("선택자가 없으면 null 이 나온다 (조용히 통과하지 않는다)",
    글씨크기('".tl-nope{color:red;}"', ".tl-없는것") === null);
}

