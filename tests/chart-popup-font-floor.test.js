절("[2] ★이 파일들에 작은 글씨가 새로 생기지 않았는가★");
{
  /* 한 자리를 올려놓고 바로 옆에 작은 것을 새로 만드는 것을 막습니다.
   *
   * ⚠️ 남아 있는 것 — js/chart-replay.js 에 16px 이 ★7군데★ 있습니다.
   *      .tl-rp-hint · .tl-rp-banner · .tl-rp-menu button · .tl-rp-toast ·
   *      .tl-rp-lock .s(@media) · .tl-rp-mlock · .tl-rp-mlock button
   *    ★2026-09-03 수리팀 배정(16곳)에 안 들어 있어 안 건드렸습니다.★
   *    PM 에게 따로 보고했습니다. 배정이 오면 그때 17 로 올리면 되고,
   *    그때 ★이 검사는 손댈 필요가 없습니다★ — 개수가 줄어드는 건 통과입니다.
   *
   * 그래서 두 가지를 봅니다.
   *   (a) 어느 파일에도 ★16px 미만★ 은 없다 — 예외 없는 하드 바닥
   *   (b) 17px 미만 개수가 ★지금보다 늘지 않는다★ — 새로 만드는 것을 막습니다
   */
  const 하드바닥 = 16;
  const 남은한도 = { "js/chart-replay.js": 7 };

  Object.keys(소스).forEach((f) => {
    const 값들 = (소스[f].match(/font-size:\s*(\d+(?:\.\d+)?)px/g) || [])
      .map((s) => Number(/(\d+(?:\.\d+)?)/.exec(s)[1]));

    const 너무작음 = 값들.filter((v) => v < 하드바닥);
    ok(f.replace("js/", "") + " 에 " + 하드바닥 + "px 미만이 하나도 없다",
      너무작음.length === 0,
      너무작음.length ? "작은 값 " + 너무작음.join(" / ") + "px 이 있습니다" : "");

    const 한도 = 남은한도[f] || 0;
    const 미만 = 값들.filter((v) => v < 바닥);
    ok(f.replace("js/", "") + " 의 " + 바닥 + "px 미만이 " + 한도 + "개 이하다 (늘리지 마세요)",
      미만.length <= 한도,
      "지금 " + 미만.length + "개 (" + 미만.join(",") + "px) — 한도 " + 한도 + "개");
  });
}

/* ===================================================================== */
절("[3] ★좁은 화면이라고 글씨를 줄이지 않았는가★ — 지난 세 번의 실패 경로");
{
  /* 좁은 폭 @media 안에서 14px 이하가 나오면 그건 "안 들어가서 줄인" 것입니다.
     푸는 순서는 ① 폭 넓히기 ② 두 줄 ③ 창 안 스크롤 ④ 여백 ⑤ 글씨(최후) 입니다. */
  Object.keys(소스).forEach((f) => {
    /* 15px 이하 = "안 들어가서 줄인" 것으로 봅니다.
       16px 은 위 [2] 가 ★개수★ 로 잡고 있습니다 — 여기서 또 잡으면 같은 것을 두 번 셉니다. */
    const 나쁨 = /@media[^{]*max-width[^]{0,1200}?font-size:\s*(?:[0-9]|1[0-5])px/.test(소스[f]);
    ok(f.replace("js/", "") + " 의 좁은 폭 @media 가 글씨를 낮추지 않는다",
      !나쁨,
      "@media max-width 근처에 15px 이하가 있습니다 — 줄이지 말고 폭·줄바꿈·스크롤로 푸세요");
  });
}

