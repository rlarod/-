"use strict";

const fs = require("fs");
const path = require("path");

/* ⚠️ tests/repo-env-honored.test.js 가 이 모양을 강제합니다 —
   고정으로 박으면 돌연변이 검증이 사본이 아니라 진짜 저장소를 읽어 거짓 통과합니다. */
const REPO = process.env.REPO || path.resolve(__dirname, "..");
function 읽기(p) {
  return fs.readFileSync(path.join(REPO, p), "utf8");
}

let pass = 0, fail = 0;
const 실패목록 = [];
function ok(제목, 조건, 도움말) {
  if (조건) { pass++; console.log("  ✓ " + 제목); }
  else { fail++; 실패목록.push(제목); console.log("  X " + 제목 + (도움말 ? " -> " + 도움말 : "")); }
}
function 절(t) { console.log("\n" + t); }

/* 바닥값 — 이 아래로 내려가면 안 됩니다 */
const 바닥 = 17;
const 대상 = "js/chart-replay.js";
const SRC = 읽기(대상);

/* ---------------------------------------------------------------------
 * CSS 가 "..." + 색이름 + "..." 로 ★쪼개져 붙습니다★.
 * 정규식 하나로 훑으면 따옴표에서 끊깁니다.
 * 선택자가 나오는 자리부터 잘라서 그 안의 첫 font-size 를 봅니다.
 * ------------------------------------------------------------------- */
function 글씨크기(본문, 선택자) {
  const i = 본문.indexOf(선택자 + "{");
  if (i < 0) return null;
  const m = /font-size:\s*(\d+(?:\.\d+)?)px/.exec(본문.slice(i, i + 600));
  return m ? Number(m[1]) : null;
}
function 값들(본문) {
  return (본문.match(/font-size:\s*(\d+(?:\.\d+)?)px/g) || [])
    .map((s) => Number(/(\d+(?:\.\d+)?)/.exec(s)[1]));
}
/* 좁은 폭 @media 블록만 잘라냅니다 */
function 폰블록(본문) {
  const i = 본문.indexOf("@media (max-width:560px)");
  if (i < 0) return null;
  const j = 본문.indexOf("}\",", i);
  return j < 0 ? null : 본문.slice(i, j + 3);
}

console.log("==========================================================");
console.log(" 리플레이 글씨 바닥값 " + 바닥 + "px + 역전 금지");
console.log("==========================================================");

/* ===================================================================== */
절("[1] 2026-09-03 에 올린 7곳이 " + 바닥 + "px 이상인가");
{
  /* ⚠️ 값을 못 박지 않습니다. 바닥만 봅니다 — 더 키우면 그냥 통과입니다. */
  const 자리 = [
    [".tl-rp-hint", "리플레이 안내줄 (봉 고르세요)"],
    [".tl-rp-banner", "리플레이 안내줄 (진행 중 · 시고저종)"],
    [".tl-rp-menu button", "배속 목록 항목 (0.5x ~ 10x)"],
    [".tl-rp-toast", "알림 쪽지 (포지션이 생겨 껐습니다 등)"],
    [".tl-rp-mlock", "폰 아래 주문 잠금 막대 글씨"],
    [".tl-rp-mlock button", "폰 아래 주문 잠금 막대 단추"]
  ];
  자리.forEach(function (쌍) {
    const sel = 쌍[0], 무엇 = 쌍[1];
    const v = 글씨크기(SRC, sel);
    ok(무엇 + "  " + sel, v !== null && v >= 바닥,
      v === null ? "선택자를 못 찾았습니다 — 이름이 바뀌었나요?" : "지금 " + v + "px");
  });

  /* 일곱째는 @media 안에 있습니다 — 기본쪽과 이름이 같아 따로 봅니다 */
  const 폰 = 폰블록(SRC);
  ok("좁은 폭 @media 블록을 찾았다", 폰 !== null, "블록 이름이 바뀌었습니다");
  if (폰) {
    const v = 글씨크기(폰, " .tl-rp-lock .s");
    ok("주문 잠금 안내 본문 (폰)  .tl-rp-lock .s @media", v !== null && v >= 바닥,
      v === null ? "못 찾았습니다" : "지금 " + v + "px");
  }
}

/* ===================================================================== */
절("[2] ★파일 전체★ 에 " + 바닥 + "px 미만이 하나도 없는가 (한도 0)");
{
  const 전부 = 값들(SRC);
  ok("font-size 를 실제로 찾았다 (0개면 정규식이 헛돈 것)", 전부.length >= 10,
    "찾은 개수 " + 전부.length);
  const 미만 = 전부.filter(function (v) { return v < 바닥; });
  ok(대상 + " 에 " + 바닥 + "px 미만이 0개다",
    미만.length === 0,
    "지금 " + 미만.length + "개 (" + 미만.join(",") + "px) — 한도 0개");

  /* ⚠️ chart-popup-font-floor.test.js 는 이 파일에 7개까지 열어뒀습니다.
     여기서 0 으로 조입니다. 그쪽을 고칠 필요는 없습니다(개수가 줄면 통과). */
}

/* ===================================================================== */
절("[3] ★역전 금지★ — 좁은 폭이 넓은 화면보다 크면 안 된다");
{
  const 폰 = 폰블록(SRC);
  ok("좁은 폭 @media 블록을 찾았다", 폰 !== null, "블록 이름이 바뀌었습니다");
  if (폰) {
    /* 폰 블록에 글씨를 정한 선택자를 전부 뽑아 기본값과 맞대어 봅니다 */
    const 겹치는것 = [".tl-rp-hint", ".tl-rp-banner", ".tl-rp-lock .t", ".tl-rp-lock .s"];
    let 잰개수 = 0;
    겹치는것.forEach(function (sel) {
      const 기본 = 글씨크기(SRC, sel);
      const 폰값 = 글씨크기(폰, " " + sel);
      if (기본 === null || 폰값 === null) {
        ok(sel + " 의 기본·폰 값을 둘 다 찾았다", false,
          "기본=" + 기본 + " / 폰=" + 폰값 + " — 이름이 바뀌었나요?");
        return;
      }
      잰개수++;
      ok(sel + " 가 역전이 아니다 (폰 " + 폰값 + "px <= 기본 " + 기본 + "px)",
        폰값 <= 기본,
        "폰이 넓은 화면보다 " + (폰값 - 기본) + "px 큽니다 — 한쪽만 올린 흔적입니다");
      ok(sel + " 폰 값이 바닥 " + 바닥 + "px 이상이다", 폰값 >= 바닥, "지금 " + 폰값 + "px");
    });
    ok("역전을 실제로 잰 선택자가 4개다", 잰개수 === 4, "잰 개수 " + 잰개수);
  }
}

/* ===================================================================== */
절("[4] px 말고 다른 단위로 우회하지 않았는가");
{
  /* [1][2] 가 px 만 셉니다. em·rem·pt·% 로 적으면 통째로 빠져나갑니다. */
  const 딴단위 = SRC.match(/font-size:\s*[\d.]+\s*(?:r?em|pt|%)/g) || [];
  ok("font-size 를 px 로만 적었다", 딴단위.length === 0,
    "px 아닌 것: " + 딴단위.join(" / ") + " — 이 검사가 못 셉니다");
}

/* ===================================================================== */
절("[5] 돌연변이 자체검증 — 이 검사가 진짜 잡는가");
{
  /* 실제 파일은 안 건드립니다. 글자만 지어내 검사 함수에 먹입니다. */
  const 가짜작게 = '".tl-rp-menu button{color:#E7ECF5; font-size:16px; padding:9px 20px;}"';
  ok("16px 으로 되돌리면 [1] 이 빨개진다",
    글씨크기(가짜작게, ".tl-rp-menu button") < 바닥,
    "안 잡혔습니다 — 검사가 헛돕니다");

  const 가짜크게 = '".tl-rp-menu button{color:#E7ECF5; font-size:22px; padding:9px 20px;}"';
  ok("더 키우면 [1] 이 안 빨개진다 (바닥이지 천장이 아니다)",
    글씨크기(가짜크게, ".tl-rp-menu button") >= 바닥,
    "천장처럼 굴고 있습니다 — 대표가 더 키우라고 할 때마다 이 파일을 고쳐야 합니다");

  /* 역전 — 기본 16 / 폰 17 로 되돌린 가짜 소스 */
  const 가짜역전 =
    '".tl-rp-hint{padding:8px 14px; font-size:16px;}",\n' +
    '"@media (max-width:560px){ .tl-rp-hint{font-size:17px; padding:7px 10px;} }",';
  const g = 글씨크기(가짜역전, ".tl-rp-hint");
  const p = 글씨크기(폰블록(가짜역전) || "", " .tl-rp-hint");
  ok("기본 16 / 폰 17 로 되돌리면 [3] 이 역전을 잡는다",
    g === 16 && p === 17 && !(p <= g),
    "기본=" + g + " 폰=" + p + " — 역전 검사가 헛돕니다");

  ok("딴 단위를 쓰면 [4] 가 빨개진다",
    /font-size:\s*[\d.]+\s*(?:r?em|pt|%)/.test('".tl-rp-hint{font-size:0.8rem;}"'),
    "안 잡혔습니다 — 단위를 바꾸면 통째로 빠져나갑니다");

  ok("선택자가 없으면 null 이 나온다 (조용히 통과하지 않는다)",
    글씨크기('".tl-nope{color:red;}"', ".tl-없는것") === null);

  ok("@media 블록이 없으면 null 이 나온다",
    폰블록('".tl-rp-hint{font-size:17px;}"') === null);
}

/* ===================================================================== */
절("[6] 실행 목록 등록");
{
  const order = 읽기("tests/_order.txt");
  ok("tests/_order.txt 에 있다",
    order.indexOf("tests/chart-replay-font-floor.test.js") !== -1,
    "빠지면 npm test 가 이 파일을 안 돌립니다");
}

