/* URL 의 //(https:// · wss://)는 주석이 아닙니다. 앞에 : 가 붙습니다. */
const BS = String.fromCharCode(92);
const 줄주석패턴 = BS + "/" + BS + "/";
const 블록주석패턴 = BS + "/" + BS + "*";
const URL패턴 = ":" + BS + "/" + BS + "/";

/* 주석을 걷어내는 도우미(줄 단위 마스크) — 블록 주석 안의 줄을 골라내려고 씁니다. */
function 주석줄표시(src) {
  const lines = src.split(/\r?\n/);
  const 표시 = new Array(lines.length).fill(false);
  let 블록안 = false;
  lines.forEach((l, i) => {
    const t = l.trim();
    if (블록안) {
      표시[i] = true;
      if (l.indexOf("*/") !== -1) 블록안 = false;
      return;
    }
    if (t.indexOf("/*") === 0) {
      표시[i] = true;
      if (l.indexOf("*/", l.indexOf("/*") + 2) === -1) 블록안 = true;
      return;
    }
    if (t.indexOf("//") === 0 || t.indexOf("*") === 0) 표시[i] = true;
  });
  return 표시;
}

/* 한 줄이 "주석 글자를 검사 대상으로 삼았는가" 를 판정합니다. */
function 주석기대는검사인가(line) {
  let l = line;
  /* URL 의 // 를 먼저 지웁니다 — https:// · wss:// 는 주석이 아닙니다 */
  while (l.indexOf(URL패턴) !== -1) l = l.replace(URL패턴, ":");
  if (l.indexOf(줄주석패턴) === -1 && l.indexOf(블록주석패턴) === -1) return false;
  /* URL 은 주석이 아닙니다 — https:// · wss:// · (https?:)?// 같은 것들.
     2026-08-31 실측 — 이 줄들이 오탐으로 잡혔습니다:
       html-assets-tracked.test.js  const isRemote = (u) => /^(https?:)?[/][/]/.test(u);
       stream-signals.test.js       wss?://... · supabase-client-seal.test.js  https://...supabase.co
     앞에 : 가 붙는 것만 걸러서는 (https?:)? 처럼 괄호가 낀 형태를 못 거릅니다. */
  if (/http|wss|ws:/.test(l)) return false;
  /* 주석을 ★걷어내는★ 쪽이면 올바른 사용입니다 */
  if (/\.(replace|split|filter|map)\(/.test(l)) return false;
  /* 실제로 무언가를 검사하는 줄만 */
  return /\.(test|exec|match)\(/.test(l);
}

