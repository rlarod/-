"use strict";

const fs = require("fs");
const path = require("path");
const { boot, REPO } = require("./harness.js");

const ESC = String.fromCharCode(27);
const MARK_OK = ESC + "[32m" + "✓" + ESC + "[0m";
const MARK_NG = ESC + "[31m" + "✗" + ESC + "[0m";

let pass = 0;
let fail = 0;
function ok(name, cond, detail) {
  if (cond) { pass++; console.log("  " + MARK_OK + " " + name); }
  else { fail++; console.log("  " + MARK_NG + " " + name + (detail ? " — " + detail : "")); }
}
function section(t) { console.log("\n" + t); }

const 진입가 = 60000;
/* 창이 보여주는 자릿수만큼은 벌어질 수 있습니다. 그보다 크게 벌어지면 계산이 다른 것입니다.

   ⚠️ 2026-08-31 [B건] — 예전에는 오차를 0.005 하나로 뒀습니다. 그때는 폭이 전부
      1% 미만이라 창이 늘 소수 2자리로 찍었기 때문입니다(0.126% → "0.13%").
      구간 상한이 생기면서 배율이 내려가 폭이 1% 를 넘게 됐고, 창은 그때
      ★소수 1자리★ 로 찍습니다(1.125% → "1.1%"). 옛 오차로는 그 반올림만으로
      빨강이 났습니다 — 계산이 틀린 게 아니라 ★자릿수를 잘못 안 것★ 입니다.
      js/leverage-modal.js 가 쓰는 규칙(청산폭 < 1 ? 2자리 : 1자리)에 맞춥니다. */
const 표시오차of = (값) => (값 < 1 ? 0.005 : 0.05) + 1e-9;

/* 레버리지 창까지 올린 무대 — index.html 순서 그대로입니다. */
function 무대() {
  const env = boot({ extra: ["js/leverage-gate.js", "js/leverage-modal.js"] });
  if (env.App.LeverageGate && typeof env.App.LeverageGate.init === "function") {
    env.App.LeverageGate.init();
  }
  env.App.LeverageModal.init();
  env.App.Bus.emit("price:update", { symbol: "BTCUSDT", price: 진입가, time: Date.now() });
  env.App.LeverageModal.open();

  const 문구 = () => env.doc.getElementById("lev-modal-warn").textContent;
  const 수량넣기 = (v) => {
    const q = env.doc.getElementById("order-qty-input");
    if (q) q.value = v === null ? "" : String(v);
  };
  const 배율고르기 = (n) => env.App.LeverageModal._setPending(n);
  /* 문구에서 % 숫자를 뽑습니다. 없으면 null. */
  const 말한폭 = () => {
    const m = /([\d.]+)\s*%/.exec(문구());
    return m ? parseFloat(m[1]) : null;
  };
  /* 엔진이 실제로 잡는 버팀폭 — calcLiquidationPrice 를 그대로 씁니다. */
  const 엔진폭 = (n, qty) => {
    const liq = env.App.Trading.calcLiquidationPrice("long", 진입가, n, qty * 진입가);
    return ((진입가 - liq) / 진입가) * 100;
  };
  /* ⭐ 2026-08-31 [B건] — 창이 배율을 깎을 수 있으므로, "내가 부탁한 배율" 이 아니라
     ★창이 실제로 정한 배율★ 을 문구에서 읽습니다. 문구는 "50배 — ..." 로 시작합니다. */
  const 고른배율 = () => {
    const m = /^([0-9]+)배/.exec(문구());
    return m ? parseInt(m[1], 10) : null;
  };
  const 프리셋 = () =>
    Array.prototype.map.call(
      env.doc.querySelectorAll("#lev-modal-presets .lev-preset"),
      (b) => Number(b.dataset.v)
    );
  const 슬라이더상한 = () => Number(env.doc.getElementById("lev-modal-range").max);
  const 눈금글자 = () => env.doc.getElementById("lev-modal-max").textContent;
  const 안내 = () => env.doc.getElementById("lev-modal-note").textContent;
  return { env, 문구, 수량넣기, 배율고르기, 말한폭, 엔진폭, 고른배율, 프리셋, 슬라이더상한, 눈금글자, 안내 };
}

/* ========================================================================
 * 1. 주문 규모를 모를 때 — 숫자를 말하지 않는다
 * ====================================================================== */
section("1. 수량을 아직 안 넣었을 때");
{
  const S = 무대();
  S.수량넣기(null);
  S.배율고르기(100);

  ok("아무 % 숫자도 말하지 않는다", S.말한폭() === null, S.문구());
  ok("대신 주문 규모에 따라 달라진다고 알려준다",
    /규모|크기/.test(S.문구()), S.문구());
  ok("무엇을 하면 되는지 알려준다 (수량 입력)", /수량/.test(S.문구()), S.문구());
  ok("배율은 그대로 말해준다", /^100배/.test(S.문구()), S.문구());

  /* 옛 고장 그대로면 여기서 터집니다 — 0.5% 는 1구간에도 4구간에도 없는 값입니다. */
  ok("옛 고정값 0.50% 를 말하지 않는다", !/0\.50\s*%/.test(S.문구()), S.문구());
}

/* ========================================================================
 * 2. 주문 규모를 알 때 — 엔진과 똑같이 말한다
 * ====================================================================== */
section("2. 수량을 넣었을 때 (창 == 엔진)");
{
  const S = 무대();

  /* [1구간] 0.1 BTC × 60,000 = 명목 6,000 (0~300,000) */
  S.수량넣기(0.1);
  S.배율고르기(100);
  const 창1 = S.말한폭();
  const 엔진1 = S.엔진폭(100, 0.1);
  ok("1구간 · 100배 — 창이 숫자를 말한다", 창1 !== null, S.문구());
  ok("1구간 · 100배 — 창이 말하는 폭이 엔진과 같다",
    창1 !== null && Math.abs(창1 - 엔진1) <= 표시오차of(엔진1),
    "창 " + 창1 + "% vs 엔진 " + 엔진1.toFixed(3) + "%");

  /* [4구간] 160 BTC × 60,000 = 명목 9,600,000 (3,000,000~12,000,000)
     ⚠️ 2026-08-31 [B건] — 이 구간의 최대 배율은 ★50배★ 입니다.
        100 을 부탁해도 창이 50 으로 깎습니다. 그게 맞는 동작입니다. */
  S.수량넣기(160);
  S.배율고르기(100);
  ok("4구간에서 100배를 고르면 창이 ★50배로 깎는다★ (구간 상한)",
    S.고른배율() === 50, "창이 고른 배율: " + S.고른배율() + " / 문구: " + S.문구());
  const 배율4 = S.고른배율();
  const 창4 = S.말한폭();
  const 엔진4 = S.엔진폭(배율4, 160);
  ok("4구간 — 창이 말하는 폭이 ★창이 실제로 고른 배율★ 기준 엔진과 같다",
    창4 !== null && Math.abs(창4 - 엔진4) <= 표시오차of(엔진4),
    "창 " + 창4 + "% (" + 배율4 + "배) vs 엔진 " + 엔진4.toFixed(3) + "%");
  /* ⚠️ 이게 진짜 무서운 경우입니다 — 창은 50배 폭을 말해놓고 주문은 100배로 나가는 것.
     그러면 회원은 1.1% 버틴다고 믿는데 실제로는 0.125% 에서 청산됩니다. */
  ok("창이 100배 기준 폭(약 0.125%)을 말하고 있지는 않다",
    창4 !== null && Math.abs(창4 - S.엔진폭(100, 160)) > 표시오차of(S.엔진폭(100, 160)),
    "창 " + 창4 + "% 가 100배 폭과 같습니다 — 깎은 배율과 말하는 폭이 어긋납니다");

  /* ── (가) 새 성질 — ★고를 수 없는 배율은 창이 아예 안 보여준다★ ────────
     회원이 못 고르는 값을 눈앞에 두면, 눌렀다가 조용히 깎이거나 주문에서
     거절당합니다. 창에서 아예 지웁니다. */
  ok("4구간 — 프리셋에 50배 초과가 하나도 없다",
    S.프리셋().every((v) => v <= 50), S.프리셋().join(","));
  ok("4구간 — 프리셋에 50배는 남아 있다 (있는 것까지 지우면 안 됩니다)",
    S.프리셋().indexOf(50) >= 0, S.프리셋().join(","));
  ok("4구간 — 슬라이더 상한도 50", S.슬라이더상한() === 50, String(S.슬라이더상한()));
  ok("4구간 — 눈금 글자도 50x", S.눈금글자() === "50x", S.눈금글자());
  ok("4구간 — 왜 내려갔는지 안내가 이유를 말해준다 (주문 금액 · 50배)",
    /주문 금액/.test(S.안내()) && /50배/.test(S.안내()), S.안내());

  /* ── (나) 원래 성질 — 같은 배율인데 주문이 크면 더 좁다 ─────────────
     ⚠️ 2026-08-31 [B건] — 예전에는 둘 다 100배로 비교했습니다. 이제 큰 주문은
        100배를 못 고르므로 ★둘 다 고를 수 있는 50배★ 로 맞춰서 비교합니다.
        배율이 서로 다르면(100 vs 50) 배율 차이가 구간 차이를 덮어써서
        "큰 주문이 더 넓다" 는 거짓 결론이 나옵니다. */
  S.수량넣기(0.1);
  S.배율고르기(50);
  const 작은50 = S.말한폭();
  ok("작은 주문도 50배로 고를 수 있다", S.고른배율() === 50, String(S.고른배율()));
  S.수량넣기(160);
  S.배율고르기(50);
  const 큰50 = S.말한폭();
  ok("큰 주문도 50배로 고를 수 있다 (4구간 상한이 정확히 50)", S.고른배율() === 50, String(S.고른배율()));
  ok("⭐ 같은 50배라도 주문이 크면 더 좁은 폭을 말한다",
    작은50 !== null && 큰50 !== null && 큰50 < 작은50,
    "작은 주문 " + 작은50 + "% / 큰 주문 " + 큰50 + "%");
  ok("옛 고장(둘 다 0.50%)이 아니다", 작은50 !== 큰50, String(작은50) + " vs " + String(큰50));

  /* 배율까지 같이 내려가므로, 회원이 실제로 겪는 폭은 오히려 넓어집니다.
     "그래서 안전해졌다" 가 아니라 ★그 금액에서 100배를 못 건다★ 는 뜻입니다. */
  ok("4구간에서 회원이 실제로 겪는 폭(50배)이 100배 폭보다 넓다",
    큰50 !== null && 큰50 > S.엔진폭(100, 160),
    큰50 + "% vs 100배였다면 " + S.엔진폭(100, 160).toFixed(3) + "%");

  S.수량넣기(0.1);
  S.배율고르기(100);

  /* 낮은 배율도 같이 봅니다 — 배율 규칙 자체는 그대로여야 합니다. */
  S.수량넣기(0.1);
  S.배율고르기(10);
  const 창10 = S.말한폭();
  ok("10배 · 1구간 — 엔진과 같다",
    창10 !== null && Math.abs(창10 - S.엔진폭(10, 0.1)) <= 표시오차of(S.엔진폭(10, 0.1)),
    "창 " + 창10 + "% vs 엔진 " + S.엔진폭(10, 0.1).toFixed(3) + "%");
  ok("배율이 낮을수록 더 넓게 버틴다고 말한다", 창10 > 창1, 창10 + "% > " + 창1 + "%");
}

/* ========================================================================
 * 3. 지정가를 적었으면 그 가격이 기준
 * ====================================================================== */
section("3. 지정가 기준");
{
  const S = 무대();
  const limit = S.env.doc.getElementById("limit-price-input");
  ok("지정가 입력칸이 있다", !!limit);
  if (limit) {
    /* 수량은 같지만 가격이 10배면 명목도 10배 → 구간이 올라갑니다.
       ⚠️ 2026-08-31 [B건] — 예전에는 둘 다 100배로 물어봤습니다. 그러면
          현재가 쪽은 3구간이라 75배로, 지정가 쪽은 4구간이라 50배로 깎여서
          ★서로 다른 배율끼리 비교★ 하게 됩니다. 실제로 0.81% → 1.1% 로
          "명목이 큰 쪽이 더 넓다" 는 거짓 결론이 나왔습니다.
          두 구간 모두 고를 수 있는 ★50배★ 로 맞춰서 비교합니다. */
    S.수량넣기(20);
    limit.value = "";
    S.배율고르기(50);
    const 현재가기준 = S.말한폭(); // 명목 1,200,000 → 3구간
    const 현재가배율 = S.고른배율();

    limit.value = "600000";
    S.배율고르기(50);
    const 지정가기준 = S.말한폭(); // 명목 12,000,000 → 4구간
    const 지정가배율 = S.고른배율();

    ok("두 경우 다 50배로 골라졌다 (배율이 같아야 구간만 비교됩니다)",
      현재가배율 === 50 && 지정가배율 === 50, 현재가배율 + " / " + 지정가배율);
    ok("지정가를 적으면 그 가격으로 명목을 잡는다", 현재가기준 !== 지정가기준,
      "현재가 " + 현재가기준 + "% / 지정가 " + 지정가기준 + "%");
    ok("명목이 커진 쪽이 더 좁다", 지정가기준 < 현재가기준,
      현재가기준 + "% → " + 지정가기준 + "%");

    /* ⭐ [B건] 새 성질 — 지정가를 적으면 ★고를 수 있는 상한도★ 같이 내려갑니다.
       명목을 지정가로 잡는다면 상한도 그 명목으로 잡아야 앞뒤가 맞습니다. */
    limit.value = "";
    S.배율고르기(100);
    const 현재가상한 = S.슬라이더상한(); // 1,200,000 → 3구간 → 75
    limit.value = "600000";
    S.배율고르기(100);
    const 지정가상한 = S.슬라이더상한(); // 12,000,000 → 4구간 → 50
    ok("지정가 기준 명목이 크면 고를 수 있는 상한도 내려간다",
      지정가상한 < 현재가상한, "현재가 " + 현재가상한 + "배 → 지정가 " + 지정가상한 + "배");
    ok("그 상한이 구간표 값과 같다 (3구간 75배 / 4구간 50배)",
      현재가상한 === 75 && 지정가상한 === 50, 현재가상한 + " / " + 지정가상한);
  }
}

/* ========================================================================
 * 4. 창이 유지증거금률을 스스로 만들어내지 않는다
 * ====================================================================== */
section("4. 값의 출처");
{
  const src = fs.readFileSync(path.join(REPO, "js", "leverage-modal.js"), "utf8");
  ok("엔진의 유지증거금을 받아 쓴다 (App.Trading.maintenanceMargin)",
    /App\.Trading\.maintenanceMargin/.test(src));
  ok("구간표를 창 안에 다시 적지 않았다 (공제액 숫자 없음)",
    !/12000|132000|482000|2982000/.test(src));
  /* 주석은 빼고 봅니다 — 주석에 옛 실측값(0.600% 같은 것)을 기록해 두는 건 괜찮습니다.
     회원에게 ★보여주는 문자열★ 안에 퍼센트가 박혀 있으면 안 됩니다.
     정규식을 문자열로 짓습니다 — 따옴표가 섞여 읽기 어려워지는 걸 피합니다. */
  const 블록주석 = new RegExp("/\\*[\\s\\S]*?\\*/", "g");
  const 줄주석 = new RegExp("^\\s*//.*$", "gm");
  const 주석뺀소스 = src.replace(블록주석, " ").replace(줄주석, " ");
  const 박힌퍼센트 = new RegExp("[\"'][^\"'\\n]*\\d(\\.\\d+)?\\s*%");
  ok("회원에게 보여주는 문구에 퍼센트를 박지 않았다",
    !박힌퍼센트.test(주석뺀소스),
    (박힌퍼센트.exec(주석뺀소스) || [""])[0]);

  /* 창이 들고 있는 기본값은 ★1구간★ 값이어야 합니다.
     (주문 규모를 모를 때만 쓰이고, 그때는 숫자를 말하지 않습니다) */
  const 기본값 = Number((src.match(/var MMR = ([\d.]+)/) || [])[1]);
  const env = boot({});
  const 엔진1구간 = env.App.Trading.maintenanceMargin(100000) / 100000;
  ok("창의 기본 유지증거금률이 엔진 1구간 값과 같다",
    Math.abs(기본값 - 엔진1구간) < 1e-9, 기본값 + " vs " + 엔진1구간);
}

