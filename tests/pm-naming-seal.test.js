function 절(제목) { console.log("\n" + 제목); }
function read(p) { return fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null; }

/* 한글 파일 이름은 자모 분리(NFD) 로 들어오는 경우가 있어 맞춰 둡니다.
   docs-sql-tracked.test.js 에서 이것 때문에 17개가 전부 오탐난 적이 있습니다. */
const NFC = (s) => (s && s.normalize ? s.normalize("NFC") : s);

/* 옛 이름 — "사업본부장" 도 "본부장" 을 품고 있으니 한 번에 걸립니다 */
