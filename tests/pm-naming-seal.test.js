/* =========================================================================
 * [3] ⭐ 살아 있는 지침에 옛 이름이 "그냥" 남아 있지 않다
 *     허용은 (가) 대표 원문 인용 (나) 새 이름 병기 (다) 운영기록 안내 뿐
 * ===================================================================== */
function 허용사유(줄) {
  if (줄.indexOf(대표원문) !== -1) return "대표 말씀 원문 인용";
  if (새이름.test(줄)) return "같은 줄에 새 이름(PM) 병기";
  if (줄.indexOf("운영기록") !== -1) return "운영기록 예외 안내";
  return null;
}
/* 한 파일에서 "그냥 남은" 옛 이름 줄만 골라냅니다 */
function 맨옛이름줄(본문) {
  const out = [];
  const 줄들 = String(본문).split(/\r?\n/);
  for (let i = 0; i < 줄들.length; i++) {
    if (!옛이름.test(줄들[i])) continue;
    if (허용사유(줄들[i])) continue;
    out.push({ 줄번호: i + 1, 내용: 줄들[i].trim() });
  }
  return out;
}

