/* ---------------------------------------------------------------------
 * 검사 대상 모으기 — 살아 있는 지침 문서만. 운영기록은 뺍니다.
 * ------------------------------------------------------------------- */
function md파일들(디렉터리, 제외) {
  const out = [];
  if (!fs.existsSync(디렉터리)) return out;
  for (const 이름 of fs.readdirSync(디렉터리)) {
    const 전체 = path.join(디렉터리, 이름);
    const rel = NFC(path.relative(REPO, 전체).split(path.sep).join("/"));
    if (제외.some((p) => rel === p || rel.indexOf(p + "/") === 0)) continue;
    const st = fs.statSync(전체);
    if (st.isDirectory()) out.push.apply(out, md파일들(전체, 제외));
    else if (/\.md$/i.test(이름)) out.push(rel);
  }
  return out;
}

const 제외경로 = ["docs/운영기록"];
const 살아있는지침 = ["CLAUDE.md"]
  .concat(md파일들(AGENTS, 제외경로))
  .concat(md파일들(path.join(REPO, "docs"), 제외경로))
  .filter((f) => fs.existsSync(path.join(REPO, f)))
  .sort();

