/** <symbol id="..."> ... </symbol> 을 { id: 그림내용 } 으로 읽습니다.
 *  ★공백만 다른 것은 같은 것으로 봅니다★ — 줄바꿈 차이로 빨개지면 아무도 안 봅니다. */
function 심볼읽기(본문) {
  const 표 = Object.create(null);
  const 차례 = [];
  const re = /<symbol\s+id="([^"]+)"([\s\S]*?)<\/symbol>/g;
  let m;
  while ((m = re.exec(본문)) !== null) {
    차례.push(m[1]);
    /* 태그 사이 줄바꿈까지 걷어냅니다 — 한 줄로 적었나 여러 줄로 적었나는
       같은 그림입니다. 거기까지 따지면 아무도 안 고치는 빨강이 됩니다. */
    표[m[1]] = m[2].replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();
  }
  return { 표: 표, 차례: 차례, 이름들: Object.keys(표).sort() };
}
/** 두 이름 목록을 견줍니다 — 한쪽에만 있는 것을 돌려줍니다 */
function 견주기(가, 나) {
  return {
    가에만: 가.filter((x) => 나.indexOf(x) === -1),
    나에만: 나.filter((x) => 가.indexOf(x) === -1)
  };
}

const SVG = 있나(SVG_경로) ? 심볼읽기(읽기(SVG_경로)) : { 표: {}, 차례: [], 이름들: [] };
