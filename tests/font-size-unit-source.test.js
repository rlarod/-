/* =========================================================================
 * [3] 실제로 뚫렸던 구멍 — 옛 정규식 vs 새 판정
 * ========================================================================= */
절("[3] ★옛 정규식이 통과시키던 것을 새 판정이 잡는가★");
{
  /* 봉인 8개가 쓰던 옛 방식 두 가지를 여기 그대로 재현해 맞대어 봅니다.
     ⚠️ 진짜 파일은 안 건드립니다 — 아래는 전부 지어낸 문자열입니다. */
  const 옛_값읽기 = function (SRC, 선택자) {
    const i = SRC.indexOf(선택자 + "{");
    if (i < 0) return null;
    const m = /font-size:\s*(\d+(?:\.\d+)?)px/.exec(SRC.slice(i, i + 600));
    return m ? Number(m[1]) : null;
  };
  const 옛_개수세기 = function (SRC) {
    return (SRC.match(/font-size:\s*(\d+(?:\.\d+)?)px/g) || [])
      .map(function (s) { return Number(/(\d+(?:\.\d+)?)/.exec(s)[1]); })
      .filter(function (v) { return v < 17; }).length;
  };

  /* (가) 옆 규칙의 17px 을 자기 값으로 읽는 경우 — 실측 재현 */
  const 사본 =
    '".tl-a{font-size:clamp(11px, 2vw, 17px);padding:6px;}",\n' +
    '".tl-b{font-size:17px;}",';
  ok("옛 방식은 clamp 를 17px 로 잘못 읽는다 (그래서 초록이었습니다)",
    옛_값읽기(사본, ".tl-a") === 17, "읽은 값 " + 옛_값읽기(사본, ".tl-a"));
  ok("옛 개수세기도 clamp 를 못 본다 (17px 미만 0개)", 옛_개수세기(사본) === 0);
  ok("★새 판정은 clamp 를 잡는다★", 글씨단위.단위위반(사본).length === 1,
    글씨단위.요약(글씨단위.단위위반(사본)));

  /* (나) rem 으로 적으면 선언 자체가 안 보이는 경우 */
  const 사본2 = '".tl-a{font-size:0.6875rem;}",\n".tl-b{font-size:17px;}",';
  ok("옛 방식은 0.6875rem(=11px) 을 17px 로 읽는다",
    옛_값읽기(사본2, ".tl-a") === 17);
  ok("★새 판정은 rem 을 잡는다★", 글씨단위.단위위반(사본2).length === 1);

  /* (다) 리플레이 봉인이 쓰던 "세 단위만 막는" 정규식 */
  const 옛_세단위 = /font-size:\s*[\d.]+\s*(?:r?em|pt|%)/;
  [
    ["clamp(11px, 2vw, 17px)", "clamp"],
    ["4vw", "vw"],
    ["2ch", "ch"],
    ["smaller", "이름값"],
    ["calc(17px - 4px)", "calc"],
    ["var(--tl-font)", "var"],
  ].forEach(function (쌍) {
    const 글 = '".tl-a{font-size:' + 쌍[0] + ';}"';
    ok("옛 세단위 정규식은 " + 쌍[1] + " 을 놓치고 새 판정은 잡는다",
      !옛_세단위.test(글) && 글씨단위.단위위반(글).length === 1,
      "옛=" + 옛_세단위.test(글) + " 새=" + 글씨단위.단위위반(글).length);
  });

  /* (라) 판정기를 통째로 무력화하는 방향 — 아무것도 안 잡게 만들면 걸립니다 */
  ok("판정기가 최소한 하나는 잡는다 (전부 통과시키는 판정이 아니다)",
    글씨단위.단위위반('".x{font-size:1em;}"').length === 1);
}

