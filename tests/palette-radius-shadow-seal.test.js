/* CSS 들에서 "--이름: 값" 정의를 전부 걷습니다.
   ★같은 이름이 여러 값으로 정의될 수 있습니다★ (밝은 모드 / 다크 모드).
   값이 서로 다르면 어느 것인지 정할 수 없으므로 ★못 푼 것으로 셉니다.★ */
function 변수표만들기(글자들) {
  var 표 = Object.create(null);
  글자들.forEach(function (항) {
    var s = 주석제거(항.글자);
    var m = s.match(/--[^\s:;{}(),]+\s*:\s*[^;}]+/g) || [];
    m.forEach(function (한줄) {
      var i = 한줄.indexOf(":");
      var 이름 = 한줄.slice(0, i).trim();
      var 값 = 한줄.slice(i + 1).trim();
      if (!표[이름]) 표[이름] = [];
      if (표[이름].indexOf(값) < 0) 표[이름].push(값);
    });
  });
  return 표;
}

function 변수풀기(값, 표, 깊이) {
  깊이 = 깊이 || 0;
  if (String(값).indexOf("var(") < 0) return { 값: String(값).trim(), 풂: true };
  if (깊이 >= 최대깊이) {
    return { 값: 값, 풂: false,
      이유: "var 사슬이 " + 최대깊이 + "단계를 넘습니다 (순환일 수 있습니다)" };
  }
  var 막힘 = null;
  var 바뀜 = String(값).replace(
    /var\(\s*(--[^\s:;{}(),]+)\s*(?:,([^()]*))?\)/g,
    function (전체, 이름, 대체) {
      var 후보 = 표[이름];
      if (후보 && 후보.length === 1) return 후보[0];
      if (후보 && 후보.length > 1) {
        막힘 = 막힘 || (이름 + " 정의가 " + 후보.length + "개라 어느 것인지 못 정합니다");
        return 전체;
      }
      if (대체 !== undefined && 대체 !== null && String(대체).trim() !== "") {
        return String(대체).trim();
      }
      막힘 = 막힘 || (이름 + " 정의를 CSS 에서 못 찾았습니다");
      return 전체;
    }
  );
  if (막힘) return { 값: 바뀜, 풂: false, 이유: 막힘 };
  if (바뀜 === String(값)) {
    return { 값: 바뀜, 풂: false, 이유: "치환해도 글자가 그대로입니다 (var() 문법이 이상합니다)" };
  }
  return 변수풀기(바뀜, 표, 깊이 + 1);
}

