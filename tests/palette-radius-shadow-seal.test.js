/* 주석을 걷어냅니다. ★안 걷으면 주석 산문에 적힌 색·값이 진짜 규칙으로 읽힙니다.★
   style.css 2747~2748 행에 팔레트 9색이 산문으로 나열돼 있고, 4072 행에는
   명암비 표에 #F0506E · #838DA4 가 또 나옵니다. 걷지 않으면 그것까지 셉니다. */
function 주석제거(s) {
  return String(s).replace(/\/\*[\s\S]*?\*\//g, "");
}

/* ★차트 파일은 안 읽습니다★ — 지표선 색은 다른 봉인 몫입니다(두 벌 금지). */
function 대상파일() {
  var 목록 = ["style.css"];
  fs.readdirSync(path.join(REPO, "css")).forEach(function (f) {
    if (f.slice(-4) === ".css" && f.indexOf("chart-") !== 0) 목록.push("css/" + f);
  });
  return 목록;
}

/* =======================================================================
 * 판정기 — 파일 글자들을 받아 숫자만 돌려줍니다.
 * ★파일을 안 읽고 문자열 배열만 받습니다.★ 그래야 [5] 에서 사본으로 돌립니다.
 * ===================================================================== */
function 재기(글자들) {
  var 선언 = Object.create(null); /* "#0D1422" -> ["--surface2", …] */
  var 모서리 = [];                /* {값, px} */
  var 그림자 = { none: 0, inset: 0, 진짜: 0, 목록: [] };

  글자들.forEach(function (항) {
    var s = 주석제거(항.글자);

    /* 팔레트 — "--이름:#RRGGBB" 선언만 봅니다. 사용처(color:#…)는 안 셉니다. */
    var d = s.match(/--[A-Za-z0-9-]+\s*:\s*#[0-9A-Fa-f]{6}/g) || [];
    d.forEach(function (한줄) {
      var 쪼갬 = 한줄.split(":");
      var 이름 = 쪼갬[0].trim();
      var 값 = 쪼갬[1].trim().toUpperCase();
      if (!선언[값]) 선언[값] = [];
      if (선언[값].indexOf(이름) < 0) 선언[값].push(이름);
    });

    /* 모서리 */
    var r = s.match(/border-radius\s*:\s*[^;}]+/g) || [];
    r.forEach(function (한줄) {
      var 값 = 한줄.replace(/border-radius\s*:\s*/, "").trim();
      var px = (값.match(/(\d+(?:\.\d+)?)px/g) || []).map(function (x) {
        return parseFloat(x);
      });
      모서리.push({ 파일: 항.이름, 값: 값, px: px });
    });

    /* 그림자 */
    var b = s.match(/box-shadow\s*:\s*[^;}]+/g) || [];
    b.forEach(function (한줄) {
      var 값 = 한줄.replace(/box-shadow\s*:\s*/, "").trim();
      if (/^none$/i.test(값)) { 그림자.none++; return; }
      if (/^inset\b/i.test(값)) { 그림자.inset++; return; }
      그림자.진짜++;
      그림자.목록.push(항.이름 + "  " + 값.slice(0, 46));
    });
  });

  return { 선언: 선언, 모서리: 모서리, 그림자: 그림자 };
}

